use super::{repo, work_branch};
use crate::ctx::Ctx;
use crate::error::KeelError;
use crate::report::HumanStep;
use crate::step::{Check, Step};
use crate::tools::{bosun, failure, gh, git};

pub struct Doctor;

const BODY_TAIL: &str = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";

fn body() -> String {
    let steps = [
        "preflight: tools at their pins",
        "apps: Claude and Renovate installed",
        "render: the template rendered with splice",
        "governance: bosun initialised, plan imported",
        "settings: repo settings applied with hoist",
        "token: the update bot's token stored",
        "agent-env: the cloud setup script",
        "doctor: `bosun doctor --remote` is clean",
    ];
    let list: Vec<String> = steps.iter().map(|s| format!("- {s}")).collect();
    format!(
        "Bootstrapped by `keel up`. Steps:\n\n{}{BODY_TAIL}",
        list.join("\n")
    )
}

/// `bosun doctor --remote`: `Some` (not clean, or cannot tell) means stop; nothing may be pushed.
fn gate(cx: &Ctx) -> Option<Check> {
    match bosun::doctor(cx.runner, &cx.dir) {
        Err(e) => return Some(Check::Failed(e)),
        Ok(bosun::Doctor::Offline) => {
            return Some(Check::Human(HumanStep {
                id: "doctor".into(),
                title: "bosun doctor ran offline: it needs a GitHub token in GH_TOKEN. \
                            Export one from gh, then run `keel up` again"
                    .into(),
                url: String::new(),
                command: "export GH_TOKEN=$(gh auth token)".into(),
            }));
        }
        // Missing items fail whatever the PR state: never push or open a PR over them.
        Ok(bosun::Doctor::Missing(m)) => {
            return Some(Check::Failed(format!(
                "bosun doctor --remote reports missing: {}",
                m.join("; ")
            )));
        }
        Ok(bosun::Doctor::Clean) => {}
    }
    None
}

impl Step for Doctor {
    fn id(&self) -> &'static str {
        "doctor"
    }

    fn check(&self, cx: &mut Ctx) -> Result<Check, KeelError> {
        repo(cx)?;
        if let Some(c) = gate(cx) {
            return Ok(c);
        }
        let repo = repo(cx)?;
        let branch = match work_branch(cx) {
            Ok(b) => b,
            Err(e) => return Ok(Check::Failed(e)),
        };
        let pr = gh::pr_view(cx.runner, &cx.dir, &repo, &branch)
            .filter(|p| p.state == "OPEN" || p.state == "MERGED");
        Ok(match pr {
            Some(p) => Check::Done(format!("bosun doctor is clean, PR #{} exists", p.number)),
            None => Check::Todo(format!("push {branch} and open a pull request")),
        })
    }

    fn apply(&self, cx: &mut Ctx) -> Result<Check, KeelError> {
        let repo = repo(cx)?;
        let r = cx.runner;
        if let Some(c) = gate(cx) {
            return Ok(c);
        }
        let default = match gh::default_branch(r, &repo) {
            Ok(b) => b,
            Err(e) => return Ok(Check::Failed(e)),
        };
        let branch = match git::ensure_branch(r, &cx.dir, &default, cx.manifest.branch_name()) {
            Ok(b) => b,
            Err(e) => return Ok(Check::Failed(e)),
        };
        // Only keel's own files; bosun and splice commit or leave theirs. Nothing owned: no commit.
        let owned: Vec<String> = ["keel.toml", ".gitignore", "Cargo.lock"]
            .into_iter()
            .filter(|p| cx.dir.join(p).exists())
            .map(String::from)
            .collect();
        if let Err(e) = git::commit_paths(r, &cx.dir, &owned, "keel: bootstrap") {
            return Ok(Check::Failed(e));
        }
        let push = crate::exec::Cmd::new("git", &["push", "-u", "origin", &branch]).dir(&cx.dir);
        let o = r.run(&push);
        if o.code != 0 {
            return Ok(Check::Failed(failure(&push, &o)));
        }
        let open = gh::pr_view(r, &cx.dir, &repo, &branch).is_some_and(|p| p.state == "OPEN");
        if !open {
            let c = gh::pr_create_cmd(&cx.dir, &repo, &branch, "keel: bootstrap", &body());
            let o = r.run(&c);
            if o.code != 0 {
                return Ok(Check::Failed(failure(&c, &o)));
            }
        }
        self.check(cx)
    }
}

#[cfg(test)]
mod tests {
    use super::super::testutil::*;
    use super::*;
    use crate::ctx::Opts;
    use crate::exec::{FakeRunner, Out};

    const CLEAN: &str = r#"{"version":1,"command":"doctor","ok":true,"exit_code":0,"data":{"items":[{"id":"a","status":"ok"}],"missing":0},"error":null,"next":[]}"#;
    const PR: &str = r#"{"number":7,"url":"https://github.com/owner/name/pull/7","state":"OPEN","headRefOid":"abc123"}"#;

    fn fake() -> FakeRunner {
        FakeRunner::new()
            .on(
                &["gh", "repo", "view"],
                Out::ok(r#"{"defaultBranchRef":{"name":"main"}}"#),
            )
            .on(
                &["git", "rev-parse", "--abbrev-ref", "HEAD"],
                Out::ok("keel/bootstrap\n"),
            )
            .on(&["bosun", "--json", "doctor"], Out::ok(CLEAN))
            .on(&["git", "status", "--porcelain"], Out::ok("?? keel.toml\n"))
            .on(&["git", "add"], Out::ok(""))
            .on(&["git", "checkout"], Out::ok(""))
            .on(&["git", "rev-parse", "--verify"], Out::with(1, "", ""))
            .on(&["git", "commit"], Out::ok(""))
            .on(&["git", "push"], Out::ok(""))
            .on(&["gh", "pr", "create"], Out::ok("https://x/pull/7\n"))
    }

    /// A checkout holding keel.toml (and nothing else keel owns).
    fn checkout() -> tempfile::TempDir {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(d.path().join("keel.toml"), "").unwrap();
        d
    }

    fn go(r: &FakeRunner, apply: bool) -> Check {
        let d = checkout();
        let mut cx = ctx(
            r,
            d.path().into(),
            manifest("rust"),
            PINS,
            Opts::default(),
            &no_sleep,
            &no_stdin,
        );
        if apply {
            Doctor.apply(&mut cx)
        } else {
            Doctor.check(&mut cx)
        }
        .unwrap()
    }

    fn lines(r: &FakeRunner) -> Vec<String> {
        r.calls().iter().map(|c| c.line()).collect()
    }

    #[test]
    fn clean_with_pr_is_done_without_pr_is_todo() {
        let r = fake().on(&["gh", "pr", "view"], Out::ok(PR));
        assert!(matches!(go(&r, false), Check::Done(m) if m.contains("#7")));
        let r = fake().on(&["gh", "pr", "view"], Out::with(1, "", "no pull requests"));
        assert!(matches!(go(&r, false), Check::Todo(_)));
    }

    #[test]
    fn missing_item_without_pr_fails_and_apply_never_pushes_or_opens_a_pr() {
        let r = fake()
            .on(&["gh", "pr", "view"], Out::with(1, "", "none"))
            .on(
                &["bosun", "--json", "doctor"],
                Out::with(1, r#"{"ok":false,"data":{"items":[{"id":"ruleset","status":"missing"}],"missing":1}}"#, ""),
            );
        assert!(matches!(go(&r, false), Check::Failed(m) if m.contains("ruleset")));
        assert!(matches!(go(&r, true), Check::Failed(_)));
        let l = lines(&r);
        assert!(
            !l.iter()
                .any(|x| x.starts_with("git push") || x.starts_with("gh pr create")),
            "{l:?}"
        );
    }

    #[test]
    fn offline_doctor_is_a_human_step_with_the_token_command() {
        let r = fake().on(
            &["bosun", "--json", "doctor"],
            Out::with(
                5,
                r#"{"ok":false,"exit_code":5,"data":{"offline":true,"missing":0}}"#,
                "",
            ),
        );
        let Check::Human(h) = go(&r, false) else {
            panic!()
        };
        assert_eq!(h.command, "export GH_TOKEN=$(gh auth token)");
        assert!(h.title.contains("keel up"));
    }

    #[test]
    fn missing_item_with_pr_fails_and_all_retries_without_all_on_exit_2() {
        let r = fake()
            .on(&["gh", "pr", "view"], Out::ok(PR))
            .on(&["bosun", "--json", "doctor", "--remote", "--all"], Out::with(2, "", "unexpected argument '--all'"))
            .on(
                &["bosun", "--json", "doctor", "--remote"],
                Out::with(
                    1,
                    r#"{"ok":false,"data":{"items":[{"id":"ruleset","status":"missing","fix":"run hoist apply"}],"missing":1}}"#,
                    "",
                ),
            );
        let Check::Failed(m) = go(&r, false) else {
            panic!()
        };
        assert!(m.contains("ruleset") && m.contains("hoist apply"), "{m}");
        assert!(lines(&r).contains(&"bosun --json doctor --remote".to_string()));
    }

    #[test]
    fn apply_commits_pushes_without_force_and_opens_the_pr() {
        // No PR before the push, a PR after the create.
        let r = fake().on(&["gh", "pr", "view"], Out::with(1, "", "none"));
        let _ = go(&r, true);
        let l = lines(&r);
        let pos = |p: &str| {
            l.iter()
                .position(|x| x.starts_with(p))
                .unwrap_or_else(|| panic!("{p} in {l:?}"))
        };
        assert!(pos("git add -- keel.toml") < pos("git commit -m keel: bootstrap -- keel.toml"));
        assert!(
            !l.iter()
                .any(|x| x.contains(" -A") || x.contains("commit -a")),
            "{l:?}"
        );
        assert!(pos("git commit") < pos("git push -u origin keel/bootstrap"));
        assert!(pos("git push") < pos("gh pr create"));
        assert!(
            !l.iter()
                .any(|x| x.contains("--force") && x.starts_with("git")),
            "{l:?}"
        );
        let c = r
            .calls()
            .into_iter()
            .find(|c| c.args.first().is_some_and(|a| a == "pr") && c.args[1] == "create")
            .unwrap();
        let i = c.args.iter().position(|a| a == "--title").unwrap();
        assert_eq!(c.args[i + 1], "keel: bootstrap");
        let b = c.args.iter().position(|a| a == "--body").unwrap();
        assert!(
            c.args[b + 1]
                .ends_with("\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")
        );
        assert!(c.args.contains(&"--head".to_string()));
    }

    #[test]
    fn nothing_keel_owned_to_commit_commits_nothing() {
        let r = fake()
            .on(&["git", "status", "--porcelain"], Out::ok(""))
            .on(&["gh", "pr", "view"], Out::ok(PR));
        let _ = go(&r, true);
        let l = lines(&r);
        assert!(
            !l.iter()
                .any(|x| x.starts_with("git add") || x.starts_with("git commit")),
            "{l:?}"
        );
        assert!(l.iter().any(|x| x.starts_with("git push")));
    }

    #[test]
    fn pr_view_gets_repo() {
        let r = fake().on(&["gh", "pr", "view"], Out::ok(PR));
        let _ = go(&r, false);
        assert!(
            lines(&r).contains(
                &"gh pr view keel/bootstrap --repo owner/name --json number,url,state,headRefOid"
                    .to_string()
            )
        );
    }

    #[test]
    fn apply_on_the_default_branch_switches_before_commit_and_push() {
        let r = fake()
            .on(
                &["git", "rev-parse", "--abbrev-ref", "HEAD"],
                Out::ok("main\n"),
            )
            .on(&["git", "fetch"], Out::ok(""))
            .on(&["gh", "pr", "view"], Out::with(1, "", "none"));
        let _ = go(&r, true);
        let l = lines(&r);
        let pos = |p: &str| l.iter().position(|x| x.starts_with(p)).unwrap();
        assert!(pos("git checkout -b keel/bootstrap") < pos("git add"));
        assert!(pos("git add") < pos("git commit"));
        assert!(l.contains(&"git push -u origin keel/bootstrap".to_string()));
        assert!(!l.iter().any(|x| x == "git push -u origin main"));
    }

    #[test]
    fn manifest_branch_equal_to_default_never_commits_or_pushes() {
        let r = fake()
            .on(
                &["git", "rev-parse", "--abbrev-ref", "HEAD"],
                Out::ok("main\n"),
            )
            .on(&["gh", "pr", "view"], Out::with(1, "", "none"));
        let mut m = manifest("rust");
        m.branch = Some("main".into());
        let mut cx = ctx(
            &r,
            ".".into(),
            m,
            PINS,
            Opts::default(),
            &no_sleep,
            &no_stdin,
        );
        assert!(
            matches!(Doctor.apply(&mut cx).unwrap(), Check::Failed(e) if e.contains("default branch"))
        );
        let l = lines(&r);
        assert!(
            !l.iter()
                .any(|x| x.starts_with("git commit") || x.starts_with("git push"))
        );
    }

    #[test]
    fn an_open_pr_is_reused() {
        let r = fake().on(&["gh", "pr", "view"], Out::ok(PR));
        assert!(matches!(go(&r, true), Check::Done(_)));
        assert!(!lines(&r).iter().any(|x| x.starts_with("gh pr create")));
        assert!(
            lines(&r)
                .iter()
                .any(|x| x.starts_with("git push -u origin"))
        );
    }

    #[test]
    fn push_failure_is_failed() {
        let r = fake()
            .on(&["gh", "pr", "view"], Out::with(1, "", ""))
            .on(&["git", "push"], Out::with(1, "", "rejected"));
        assert!(matches!(go(&r, true), Check::Failed(m) if m.contains("rejected")));
        assert!(!lines(&r).iter().any(|x| x.starts_with("gh pr create")));
    }
}
