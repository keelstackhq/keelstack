    #[test]
    fn apply_on_the_default_branch_switches_before_commit_and_push() {
        let r = fake()
            .on(
                &["git", "rev-parse", "--abbrev-ref", "HEAD"],
                Out::ok("main\n"),
            )
            .on(&["git", "fetch"], Out::ok(""))
            .on(&["gh", "pr", "view"], Out::with(1, "", "none"));
        let _ = go(&r, true);
        let l = lines(&r);
        let pos = |p: &str| l.iter().position(|x| x.starts_with(p)).unwrap();
        assert!(pos("git checkout -b keel/bootstrap") < pos("git add"));
        assert!(pos("git add") < pos("git commit"));
        assert!(l.contains(&"git push -u origin keel/bootstrap".to_string()));
        assert!(!l.iter().any(|x| x == "git push -u origin main"));
    }

    #[test]
    fn manifest_branch_equal_to_default_never_commits_or_pushes() {
        let r = fake()
            .on(
                &["git", "rev-parse", "--abbrev-ref", "HEAD"],
                Out::ok("main\n"),
            )
            .on(&["gh", "pr", "view"], Out::with(1, "", "none"));
        let mut m = manifest("rust");
        m.branch = Some("main".into());
        let mut cx = ctx(
            &r,
            ".".into(),
            m,
            PINS,
            Opts::default(),
            &no_sleep,
            &no_stdin,
        );
        assert!(
            matches!(Doctor.apply(&mut cx).unwrap(), Check::Failed(e) if e.contains("default branch"))
        );
        let l = lines(&r);
        assert!(
            !l.iter()
                .any(|x| x.starts_with("git commit") || x.starts_with("git push"))
        );
    }

