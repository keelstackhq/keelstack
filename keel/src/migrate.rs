/// One path `splice check --json` reports as drifted, with where it comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Drift {
    path: String,
    class: String,
    /// `None` for the main template, else the channel name.
    channel: Option<String>,
    cause: String,
}

impl Drift {
    fn source(&self) -> String {
        match &self.channel {
            Some(c) => format!("channel {c}"),
            None => "main template".into(),
        }
    }

    /// Same path with the same cause (a file edited on the base stays "the same" drift).
    fn same_as(&self, o: &Drift) -> bool {
        self.path == o.path && self.cause == o.cause
    }

    /// What the owner can do about it, in splice's own words (reference.md, Channels).
    fn choices(&self) -> String {
        match (&self.channel, self.path.contains('#')) {
            (Some(c), true) => format!(
                "revert your edit between the splice markers of {h} (`git diff <base> -- {h}` shows it); `splice update --channel {c} --force` rewrites a block only when the channel has a newer version; to keep different text, change the channel's source",
                h = self.path.split('#').next().unwrap_or("")
            ),
            (Some(c), false) => format!(
                "keep local: `splice update --channel {c} --exclude {p}` (replaces that channel's stored filters; keep the ones in .splice/channels/{c}.toml); take template: `splice update --channel {c} --force`",
                p = self.path
            ),
            (None, _) => "keep local: move the local notes into the seed file the template provides (e.g. `<target>/CLAUDE.md`), then `splice update --force`; take template: `splice update --force`".into(),
        }
    }
}

/// The paths a refused `splice update` names (`` `P` is owned by X but was edited locally ``).
/// None when the refusal has any other line (broken markers, filters, ...) or names no path: that
/// is not drift on the base and must fail.
fn refusal_paths(v: &Value) -> Option<Vec<String>> {
    let mut paths = Vec::new();
    for m in v["messages"].as_array()?.iter().filter_map(Value::as_str) {
        if m.starts_with("nothing was written") {
            continue;
        }
        if !(m.contains("` is owned by ") && m.ends_with("was edited locally")) {
            return None;
        }
        let rest = &m[m.find('`')? + 1..];
        paths.push(rest[..rest.find('`')?].to_string());
    }
    (!paths.is_empty()).then_some(paths)
}

/// The drifted paths of a `splice --json check` report (`changes` + the message that names each).
fn parse_drift(v: &Value) -> Vec<Drift> {
    let msgs: Vec<&str> = v["messages"]
        .as_array()
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    v["changes"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|c| {
                    let path = c["path"].as_str()?.to_string();
                    let needle = format!("`{path}`");
                    let msg = msgs.iter().find(|m| m.contains(&needle)).copied();
                    // A section block is reported as `HOST#CHANNEL`: the channel is the suffix.
                    let channel = match path.split_once('#') {
                        Some((_, name)) => Some(name.to_string()),
                        None => msg.and_then(|m| {
                            let rest = m.strip_prefix("channel ")?;
                            let (name, _) = rest.split_once(": ")?;
                            Some(name.to_string())
                        }),
                    };
                    let cause = if path.contains('#') {
                        "block edited, deleted or broken"
                    } else if c["action"] == "conflict" {
                        "unresolved conflict markers"
                    } else if msg.is_some_and(|m| m.contains("was deleted")) {
                        "deleted"
                    } else {
                        "edited locally"
                    };
                    Some(Drift {
                        path,
                        class: c["class"].as_str().unwrap_or("owned").to_string(),
                        channel,
                        cause: cause.into(),
                    })
                })
                .collect()
        })
        .unwrap_or_default()
}

impl Mig<'_> {
    fn tool(&self, prog: &str, args: &[&str]) -> Cmd {
        let prog = self
            .fetched
            .get(prog)
            .map_or_else(|| prog.to_string(), |p| p.to_string_lossy().into_owned());
        Cmd::new(&prog, args).dir(&self.dir).timeout(TOOL_TIMEOUT)
    }

    /// Dry-run: a tool that is not installed is fetched into the temp cache, with the checksum
    /// verification of the real install, so the plan can still be listed.
    fn fetch(&mut self, t: &str) -> Result<(), String> {
        let pin = self.pin_of(t)?;
        if self.cache.is_none() {
            self.cache = Some(
                npm::TmpDir::new("cache").map_err(|e| format!("cannot make a temp dir: {e}"))?,
            );
        }
        let dir = self.cache.as_ref().map(|c| c.path().to_path_buf());
        let bin = npm::fetch_pinned(self.r, t, &pin, &dir.unwrap_or_default())?;
        self.fetched.insert(t.to_string(), bin);
        Ok(())
    }

    fn git(&self, args: &[&str]) -> Out {
        self.r.run(&Cmd::new("git", args).dir(&self.dir))
    }

    fn human(&mut self, id: &str, title: String, url: &str, command: &str) {
        self.raw.push(HumanStep {
            id: id.into(),
            title,
            url: url.into(),
            command: command.into(),
        });
    }

    /// Stage and commit what the steps changed (in the worktree); false when nothing changed.
    /// A file the repo's own ignore rules as of the base would ignore is never staged, even when a
    /// step rewrote `.gitignore` so that it no longer is: that step fails instead.
    fn commit_all(&mut self, message: &str) -> Result<bool, String> {
        let ignored_by_base = self.ignored_by_base_rules();
        let add = Cmd::new("git", &["add", "-A"]).dir(&self.dir);
        let o = self.r.run(&add);
        if o.code != 0 {
            return Err(failure(&add, &o));
        }
        let staged = self.git(&["diff", "--cached", "--name-only", "-z"]);
        let bad: Vec<String> = staged
            .stdout
            .split('\0')
            .filter(|p| !p.is_empty() && ignored_by_base.iter().any(|i| i == p))
            .map(String::from)
            .collect();
        if !bad.is_empty() {
            let mut a = vec!["reset", "-q", "--"];
            a.extend(bad.iter().map(String::as_str));
            let _ = self.git(&a);
            return Err(format!(
                "the update would un-ignore {}: files the repo ignores would be committed. Keep them ignored (or remove them), then rerun",
                bad.join(", ")
            ));
        }
        let quiet = self.git(&["diff", "--cached", "--quiet"]);
        if quiet.code == 0 {
            return Ok(false);
        }
        let c = Cmd::new("git", &["commit", "-m", message]).dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        Ok(true)
    }

    /// The untracked files the ignore rules of HEAD (the base plus keel's own commits) ignore,
    /// found with any `.gitignore` a step modified or added put back as it is at HEAD.
    fn ignored_by_base_rules(&self) -> Vec<String> {
        let st = self.git(&["status", "--porcelain=v1", "-z", "--untracked-files=all"]);
        let mut touched: Vec<(String, Option<String>)> = Vec::new();
        for e in st.stdout.split('\0') {
            let Some((code, path)) = e.split_at_checked(3) else {
                continue;
            };
            let name = path.rsplit('/').next().unwrap_or(path);
            if name != ".gitignore" || !(code.starts_with(" M") || code == "?? ") {
                continue;
            }
            let now = std::fs::read_to_string(self.dir.join(path)).ok();
            touched.push((path.to_string(), now));
        }
        for (path, _) in &touched {
            let at_head = self.git(&["show", &format!("HEAD:{path}")]);
            let p = self.dir.join(path);
            if at_head.code == 0 {
                let _ = std::fs::write(&p, at_head.stdout);
            } else {
                let _ = std::fs::remove_file(&p);
            }
        }
        let o = self.git(&["ls-files", "-o", "-i", "--exclude-standard", "-z"]);
        let ignored: Vec<String> = o
            .stdout
            .split('\0')
            .filter(|p| !p.is_empty())
            .map(String::from)
            .collect();
        for (path, now) in &touched {
            if let Some(text) = now {
                let _ = std::fs::write(self.dir.join(path), text);
            }
        }
        ignored
    }

    fn s_tools(&mut self) -> Res {
        let wanted: Vec<&str> = [
            ("splice", self.p.splice),
            ("bosun", self.p.bosun),
            ("hoist", self.p.hoist),
        ]
        .iter()
        .filter(|(_, used)| *used)
        .map(|(t, _)| *t)
        .collect();
        if wanted.is_empty() {
            return Ok((MAction::Skipped, "no tool in use".into()));
        }
        let (mut notes, mut todo) = (Vec::new(), 0);
        for t in wanted {
            let have = version_of(&self.r.run(&Cmd::new(t, &["--version"])));
            if have.as_deref() == Some(self.target.as_str()) {
                notes.push(format!("{t} {}", self.target));
                continue;
            }
            let from = have.unwrap_or_else(|| "none".into());
            if self.dry {
                todo += 1;
                if from == "none" {
                    self.fetch(t)?;
                    notes.push(format!(
                        "{t} not installed: fetched {} into a temp cache for this plan",
                        self.target
                    ));
                } else {
                    notes.push(format!("{t} {from} -> {}", self.target));
                }
                continue;
            }
            let pin = self.pin_of(t)?;
            npm::install_pinned(self.r, t, &pin)?;
            notes.push(format!("{t} {from} -> {}", self.target));
        }
        let action = match (todo, self.dry) {
            (0, false) if notes.iter().all(|n| !n.contains("->")) => MAction::Ok,
            (0, _) => MAction::Done,
            _ => MAction::WouldRun,
        };
        Ok((action, notes.join(", ")))
    }

    /// keel's embedded sha512 when it has them for exactly this version, else the registry's.
    fn pin_of(&self, tool: &str) -> Result<ToolPin, String> {
        if let Some(p) = self.pins.tool(tool)
            && p.version == self.target
            && p.sha512.is_some()
        {
            return Ok(p);
        }
        npm::registry_pin(self.r, &self.dir, tool, &self.target)
    }

    /// `splice check` on the base with the target splice, before any update: the drift that is
    /// already there. An error (not 0/1) leaves it unknown and is noted.
    fn baseline(&mut self) {
        let c = self.tool("splice", &["--json", "check"]);
        let o = self.r.run(&c);
        match o.code {
            0 => {}
            1 => self.base_drift = json(&o).map(|v| parse_drift(&v)).unwrap_or_default(),
            _ => self.notes.push(format!(
                "baseline `splice check` could not run ({}): drift on the base is unknown, so any drift after the update fails the migration",
                failure(&c, &o)
            )),
        }
    }

    /// One `splice update`; `Ok(None)` when splice refused only because of owned files that were
    /// already drifted on the base (that source is not updated, the run goes on).
    fn splice_try(&self, extra: &[&str]) -> Result<Option<String>, String> {
        let mut a = vec!["--json", "--yes", "update"];
        a.extend(extra);
        let c = self.tool("splice", &a);
        let o = self.r.run(&c);
        match o.code {
            0 => {
                let n = json(&o)
                    .and_then(|v| v["changes"].as_array().map(|a| a.len()))
                    .unwrap_or(0);
                Ok(Some(format!("{n} file changes")))
            }
            1 => {
                let only_old = json(&o).and_then(|v| refusal_paths(&v)).is_some_and(|ps| {
                    ps.iter()
                        .all(|p| self.base_drift.iter().any(|b| &b.path == p))
                });
                if only_old {
                    return Ok(None);
                }
                Err(format!(
                    "{}; conflicts or edited owned files need a decision: run `splice update {}` by hand, \
                     resolve them, then rerun keel migrate",
                    failure(&c, &o),
                    extra.join(" ")
                ))
            }
            _ => Err(failure(&c, &o)),
        }
    }

    fn mark_not_updated(&mut self, label: &str) {
        if !self.not_updated.iter().any(|l| l == label) {
            self.not_updated.push(label.to_string());
        }
    }

    /// Every source on its own, after `--all` refused: the clean ones update, the drifted stay.
    fn update_each_source(&mut self) -> Result<String, String> {
        let mut sources: Vec<(String, Vec<String>)> = Vec::new();
        if self.dir.join(".splice/lock.toml").is_file() {
            sources.push(("main template".into(), Vec::new()));
        }
        let mut names: Vec<String> = std::fs::read_dir(self.dir.join(".splice/channels"))
            .map(|d| {
                d.filter_map(|e| e.ok())
                    .filter_map(|e| {
                        let p = e.path();
                        (p.extension()? == "toml")
                            .then(|| p.file_stem()?.to_str().map(String::from))?
                    })
                    .collect()
            })
            .unwrap_or_default();
        names.sort();
        for n in names {
            sources.push((format!("channel {n}"), vec!["--channel".into(), n]));
        }
        let mut done = Vec::new();
        for (label, args) in sources {
            if self.not_updated.contains(&label) {
                continue;
            }
            let a: Vec<&str> = args.iter().map(String::as_str).collect();
            match self.splice_try(&a)? {
                Some(d) => {
                    // splice refuses a dirty tree (never --allow-dirty): commit before the next source.
                    if self.commit_all(&format!("chore: splice update ({label})"))? {
                        done.push(format!("{label}: {d}"));
                    }
                }
                None => self.mark_not_updated(&label),
            }
        }
        Ok(done.join(", "))
    }

    fn s_splice(&mut self) -> Res {
        if !self.p.splice {
            return Ok((MAction::Skipped, "no .splice/lock.toml or channel".into()));
        }
        if self.dry {
            let c = self.tool("splice", &["--json", "check"]);
            let o = self.r.run(&c);
            return match o.code {
                0 => Ok((MAction::Ok, "up to date".into())),
                1 => Ok((
                    MAction::WouldRun,
                    "an update, drift or markers (`splice check` exits 1); `splice diff` shows them"
                        .into(),
                )),
                _ => Err(failure(&c, &o)),
            };
        }
        let mut notes = Vec::new();
        if self.p.decisions_channel {
            match self.splice_try(&["--channel", "decisions"])? {
                Some(d) => {
                    if self.commit_all("chore: sync org decisions")? {
                        notes.push(format!("decisions channel ({d})"));
                    }
                }
                None => self.mark_not_updated("channel decisions"),
            }
        }
        match self.splice_try(&["--all"])? {
            Some(d) => {
                if self.commit_all("chore: splice update to the latest template and channels")? {
                    notes.push(format!("template and channels ({d})"));
                }
            }
            // `--all` writes nothing when any source has drifted owned files: go source by
            // source, one commit each (already made by `update_each_source`).
            None => {
                let d = self.update_each_source()?;
                if !d.is_empty() {
                    notes.push(format!("source by source ({d})"));
                }
            }
        }
        if !self.not_updated.is_empty() {
            notes.push(format!(
                "NOT updated because of local edits: {}",
                self.not_updated.join(", ")
            ));
            return Ok((MAction::Pending, notes.join(", ")));
        }
        if notes.is_empty() {
            Ok((MAction::Ok, "up to date".into()))
        } else {
            Ok((MAction::Done, notes.join(", ")))
        }
    }

    fn pin_file_version(&self) -> Option<String> {
        std::fs::read_to_string(self.dir.join(".bosun/version"))
            .ok()
            .map(|s| s.trim().to_string())
    }

    fn s_bosun_pin(&mut self) -> Res {
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        if self.p.bosun_channel {
            return Ok((
                MAction::Skipped,
                "the bosun channel owns the pins; `splice update` moved them".into(),
            ));
        }
        if !self.p.setup_script {
            return Ok((MAction::Skipped, "no docs/setup-script.sh to pin".into()));
        }
        if self.dry {
            let c = self.tool("bosun", &["--json", "pin", "--to", &self.target, "--check"]);
            let o = self.r.run(&c);
            if o.code == 2 {
                // An older bosun than the target has no `pin --to`; the real run installs the target first.
                return Ok((
                    MAction::WouldRun,
                    "this bosun has no `pin --to`; the real run installs the target bosun first"
                        .into(),
                ));
            }
            if o.code != 0 {
                return Err(failure(&c, &o));
            }
            let behind = json(&o)
                .map(|v| behind_list(&v["data"]["behind"]))
                .unwrap_or_default();
            return Ok(if behind.is_empty() {
                (MAction::Ok, "pins are at npm latest".into())
            } else {
                (MAction::WouldRun, behind)
            });
        }
        let c = self.tool("bosun", &["--json", "pin", "--to", &self.target]);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        let v = json(&o).ok_or_else(|| tools::not_json(&c))?;
        let changed = behind_list(&v["data"]["changed"]);
        if let Some(have) = self.pin_file_version()
            && have != self.target
        {
            return Err(format!(
                ".bosun/version says {have} after `bosun pin --to {}`; the repo pins another release than the target: fix it by hand, then rerun",
                self.target
            ));
        }
        if self.commit_all(&format!("chore: pin keelstack tools to {}", self.target))? {
            Ok((MAction::Done, changed))
        } else {
            Ok((MAction::Ok, "pins already current".into()))
        }
    }

    fn s_hoist(&mut self) -> Res {
        if !self.p.hoist {
            return Ok((MAction::Skipped, "no hoist.toml".into()));
        }
        if !self.dir.join(".github/workflows/release.yml").is_file() {
            return Ok((MAction::Skipped, "no release workflow to refresh".into()));
        }
        let mut a = vec!["--json", "init"];
        if self.dry {
            a.push("--dry-run");
        }
        let c = self.tool("hoist", &a);
        let o = self.r.run(&c);
        match o.code {
            0 | 1 => {
                if self.dry {
                    let n = json(&o)
                        .map(|v| {
                            v["items"]
                                .as_array()
                                .map(|a| {
                                    a.iter()
                                        .filter(|i| {
                                            matches!(
                                                i["action"].as_str(),
                                                Some("create" | "update")
                                            )
                                        })
                                        .count()
                                })
                                .unwrap_or(0)
                        })
                        .unwrap_or(0);
                    return Ok(if n == 0 {
                        (MAction::Ok, "release.yml is current".into())
                    } else {
                        (
                            MAction::WouldRun,
                            format!("hoist init would rewrite {n} file(s)"),
                        )
                    });
                }
                if self.commit_all("chore: refresh the hoist release workflow")? {
                    Ok((MAction::Done, "release.yml refreshed by hoist init".into()))
                } else {
                    Ok((MAction::Ok, "release.yml is current".into()))
                }
            }
            2 => {
                // Own release workflow left alone is not a task; anything else is.
                let steps = json(&o).map(|v| human_steps(&v)).unwrap_or_default();
                let open: Vec<HumanStep> = steps
                    .into_iter()
                    .filter(|h| !h.id.starts_with("release-workflow"))
                    .collect();
                let n = open.len();
                self.raw.extend(open);
                Ok((
                    if n == 0 {
                        MAction::Ok
                    } else {
                        MAction::Pending
                    },
                    if n == 0 {
                        "release.yml is yours, left alone".into()
                    } else {
                        format!("{n} human step(s) from hoist init")
                    },
                ))
            }
            _ => {
                // The repo has nothing to release: not a task for anyone.
                if json(&o).is_some_and(|v| v["error"]["kind"] == "nothing-to-publish") {
                    return Ok((MAction::Skipped, "nothing to publish".into()));
                }
                // hoist init looks up its release tag on GitHub: offline or without a token it
                // cannot run. That must not block the migration, but it must not vanish either.
                // No command is suggested: rerunning `hoist init` would fail the same way; hoist's
                // own fix text is what the owner needs.
                let why = failure(&c, &o);
                self.human(
                    "hoist-init",
                    format!(
                        "Refresh the hoist release workflow: hoist init could not run here: {why}"
                    ),
                    "",
                    "",
                );
                Ok((MAction::Skipped, why))
            }
        }
    }

    fn snippet_now(&self) -> Option<String> {
        let c = Cmd::new("bosun", &["--json", "setup-snippet"]).dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return None;
        }
        json(&o)?["data"]["script"]
            .as_str()
            .filter(|s| !s.trim().is_empty())
            .map(String::from)
    }

    fn s_snippet(&mut self) -> Res {
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        if self.dry {
            self.snippet = Snippet {
                status: "not-checked",
                path: None,
                sha256: None,
                summary: "compared after the real run".into(),
            };
            return Ok((
                MAction::Skipped,
                "dry-run: compared after the real run".into(),
            ));
        }
        let Some(after) = self.snippet_now() else {
            return Err(
                "`bosun --json setup-snippet` printed no data.script; upgrade bosun".into(),
            );
        };
        let sha = sha256_hex(&after);
        let (status, summary) = match &self.before {
            Some(b) if *b == after => ("unchanged", "the bootstrap text is the same".to_string()),
            Some(b) => ("changed", snippet_summary(b, &after, &self.keel_dir)),
            None => (
                "unknown",
                "no earlier bosun to compare with; paste it to be safe".to_string(),
            ),
        };
        let mut path = None;
        if status != "unchanged" {
            let name = self.repo_name.clone();
            let write = |rel: &str, text: &str| -> Result<(), String> {
                let p = self.keel_dir.join(rel);
                p.parent()
                    .map_or(Ok(()), std::fs::create_dir_all)
                    .and_then(|()| std::fs::write(&p, text))
                    .map_err(|e| format!("cannot write {}: {e}", p.display()))
            };
            write(SNIPPET_FILE, &agent_env::compose(&name, &after))?;
            if let Some(b) = &self.before {
                write(SNIPPET_PREV, &agent_env::compose(&name, b))?;
            }
            let file = self.keel_dir.join(SNIPPET_FILE).display().to_string();
            path = Some(file.clone());
            self.human(
                "setup-snippet",
                format!(
                    "Paste {file} into the Setup script of your Claude Code cloud environment ({summary})"
                ),
                "https://claude.ai/code",
                &format!("cat {file}"),
            );
        }
        self.snippet = Snippet {
            status,
            path,
            sha256: Some(sha),
            summary: summary.clone(),
        };
        Ok(if status == "unchanged" {
            (MAction::Ok, summary)
        } else {
            (MAction::Pending, format!("{status}: {summary}"))
        })
    }

    /// Read-only checks of the result: `splice check` must pass; `bosun doctor` and `hoist check`
    /// findings are remote state, so they become checklist entries instead of a rollback.
    fn s_verify(&mut self) -> Res {
        let mut notes = Vec::new();
        let mut pending = false;
        if self.p.splice {
            let c = self.tool("splice", &["--json", "check"]);
            let o = self.r.run(&c);
            let now = json(&o).map(|v| parse_drift(&v)).unwrap_or_default();
            // Drift that was already on the base is the owner's to settle, not a failure of this
            // migration; only drift a step introduced (or anything that is not drift) fails it.
            let new: Vec<&Drift> = now
                .iter()
                .filter(|d| !self.base_drift.iter().any(|b| b.same_as(d)))
                .collect();
            let only_old_drift = o.code == 1 && !now.is_empty() && new.is_empty();
            // Dry-run reports the work `check` finds; the real run must end clean.
            if o.code != 0 && !self.dry && !only_old_drift {
                let named = if new.is_empty() {
                    String::new()
                } else {
                    format!(
                        " (drift the migration introduced: {})",
                        new.iter()
                            .map(|d| d.path.as_str())
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                return Err(format!(
                    "splice check still fails after the update{named}: {}",
                    failure(&c, &o)
                ));
            }
            if only_old_drift || (self.dry && !now.is_empty()) || !self.not_updated.is_empty() {
                let list = now
                    .iter()
                    .map(|d| {
                        format!(
                            "`{}` ({}, {}, {}): {}",
                            d.path,
                            d.source(),
                            d.class,
                            d.cause,
                            d.choices()
                        )
                    })
                    .collect::<Vec<_>>()
                    .join("; ");
                let head = if self.not_updated.is_empty() {
                    format!(
                        "Settle {} splice drift path(s) that were already on the base (not caused by this migration)",
                        now.len()
                    )
                } else {
                    format!(
                        "These sources were NOT updated because of local edits: {}. Resolve each path (keep local or take the template's), then rerun `keel migrate`",
                        self.not_updated.join(", ")
                    )
                };
                self.human(
                    "splice-drift",
                    format!("{head}; per path: {list}"),
                    "",
                    "splice check",
                );
                notes.push(format!(
                    "splice check: {} drifted path(s) already on the base, not caused by the migration",
                    now.len()
                ));
                pending = true;
            } else {
                notes.push(if o.code == 0 {
                    "splice check ok".to_string()
                } else {
                    "splice check: work left (dry-run)".to_string()
                });
            }
        }
        if self.p.bosun {
            let c = self.tool("bosun", &["--json", "doctor"]);
            let o = self.r.run(&c);
            match o.code {
                0 => notes.push("bosun doctor ok".into()),
                5 => notes.push("bosun doctor skipped (no GITHUB_TOKEN)".into()),
                _ => {
                    let fix = json(&o)
                        .and_then(|v| {
                            v["data"]["next_step"]
                                .as_str()
                                .or_else(|| v["error"]["fix"].as_str())
                                .map(String::from)
                        })
                        .unwrap_or_else(|| failure(&c, &o));
                    self.human(
                        "bosun-doctor",
                        format!("bosun doctor reports work left: {fix}"),
                        "",
                        "bosun doctor",
                    );
                    notes.push("bosun doctor: work left".into());
                    pending = true;
                }
            }
        }
        if self.p.hoist {
            let c = self.tool("hoist", &["--json", "check"]);
            let o = self.r.run(&c);
            match o.code {
                0 => notes.push("hoist check ok".into()),
                1 => {
                    let drift = json(&o)
                        .map(|v| {
                            hoist::items_of(&v)
                                .into_iter()
                                .filter(|i| !matches!(i.action.as_str(), "ok" | "unknown"))
                                .take(3)
                                .map(|i| format!("{}/{}", i.kind, i.key))
                                .collect::<Vec<_>>()
                                .join(", ")
                        })
                        .unwrap_or_default();
                    self.human(
                        "hoist-apply",
                        format!(
                            "hoist reports drift ({drift}); apply it with an admin token (environments such as release-tags, reviewers, rulesets)"
                        ),
                        "",
                        "hoist apply --area github",
                    );
                    notes.push("hoist check: drift".into());
                    pending = true;
                }
                2 => {
                    let steps = json(&o).map(|v| human_steps(&v)).unwrap_or_default();
                    self.raw.extend(steps);
                    notes.push("hoist check: human steps".into());
                    pending = true;
                }
                _ => {
                    self.human(
                        "hoist-check",
                        format!("hoist check could not run here: {}", failure(&c, &o)),
                        "",
                        "hoist check",
                    );
                    notes.push("hoist check skipped".into());
                    pending = true;
                }
            }
        }
        if notes.is_empty() {
            return Ok((MAction::Skipped, "nothing to verify".into()));
        }
        Ok((
            if pending {
                MAction::Pending
            } else {
                MAction::Ok
            },
            notes.join("; "),
        ))
    }

    fn s_mode(&mut self) -> Res {
        let Some(mode) = self.args.mode.clone() else {
            return Ok((MAction::Skipped, "not asked (--mode)".into()));
        };
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        let c = self.tool("bosun", &["--json", "migrate", "--to", &mode, "--dry-run"]);
        let o = self.r.run(&c);
        if o.code != 0 {
            // The migration itself is done and verified: a mode that cannot be planned here is a
            // warning with the command to run by hand, never a rollback.
            self.human(
                "bosun-mode",
                format!(
                    "After this PR merges, move bosun to mode {mode} by hand (planning it here failed: {})",
                    failure(&c, &o)
                ),
                "",
                &format!("bosun migrate --to {mode}"),
            );
            return Ok((
                MAction::Pending,
                format!("could not plan bosun migrate --to {mode}; left to a human"),
            ));
        }
        self.human(
            "bosun-mode",
            format!(
                "After this PR merges, move bosun to mode {mode} (it opens its own gated PR, owner approves)"
            ),
            "",
            &format!("bosun migrate --to {mode}"),
        );
        Ok((
            MAction::Pending,
            format!("planned: bosun migrate --to {mode}"),
        ))
    }

    /// Commits of the migration branch the base lacks (keel's, this run and any earlier run).
    fn ahead(&self) -> u32 {
        let o = self.git(&["rev-list", "--count", &format!("{}..HEAD", self.base)]);
        o.stdout.trim().parse().unwrap_or(0)
    }

    fn s_pr(&mut self) -> Res {
        if !self.args.pr {
            if self.args.branch.is_some() {
                self.push()?;
                return Ok((MAction::Done, format!("pushed to {}", self.branch)));
            }
            return Ok((MAction::Skipped, "not asked (--pr)".into()));
        }
        let c = Cmd::new("gh", &["repo", "view", "--json", "nameWithOwner"]).dir(&self.dir);
        let o = self.r.run(&c);
        let repo = json(&o)
            .and_then(|v| v["nameWithOwner"].as_str().map(String::from))
            .filter(|_| o.code == 0)
            .ok_or_else(|| failure(&c, &o))?;
        if let Some(pr) = gh::pr_view(self.r, &self.dir, &repo, &self.branch)
            && pr.state == "OPEN"
        {
            self.pr = Some(PrInfo {
                action: "existing",
                url: pr.url.clone(),
            });
            self.push()?;
            return Ok((MAction::Ok, format!("PR {} is open", pr.url)));
        }
        self.push()?;
        let title = format!("chore: migrate to keelstack v{}", self.target);
        let body = self.pr_body();
        let base = self
            .base
            .strip_prefix("origin/")
            .unwrap_or(&self.base)
            .to_string();
        let mut c = gh::pr_create_cmd(&self.dir, &repo, &self.branch, &title, &body);
        c.args.extend(["--base".to_string(), base]);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        let url = o
            .stdout
            .lines()
            .rfind(|l| l.trim().starts_with("http"))
            .unwrap_or("")
            .trim()
            .to_string();
        self.pr = Some(PrInfo {
            action: "opened",
            url: url.clone(),
        });
        Ok((MAction::Done, format!("opened {url}")))
    }

    /// Plain push, never forced. With `--branch` the worktree is detached: push HEAD to that branch.
    fn push(&self) -> Result<(), String> {
        let refspec = format!("HEAD:refs/heads/{}", self.branch);
        let c = if self.args.branch.is_some() {
            Cmd::new("git", &["push", "origin", &refspec])
        } else {
            Cmd::new("git", &["push", "-u", "origin", &self.branch])
        }
        .dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        Ok(())
    }

    fn pr_body(&self) -> String {
        let mut b = format!(
            "Moves this repo to keelstack v{} with `keel migrate`.\n\n## Steps\n",
            self.target
        );
        if !self.not_updated.is_empty() {
            b.insert_str(
                0,
                &format!(
                    "**Partial migration:** these splice sources were NOT updated because of local edits already on the base: {}. See \"Left for a human\" below; rerun `keel migrate` once resolved.\n\n",
                    self.not_updated.join(", ")
                ),
            );
        }
        if self.excluded > 0 {
            b.insert_str(
                0,
                &format!(
                    "Based on `{}`: the {} local commit(s) of `{}` that are not on it are not part of this PR.\n\n",
                    self.base,
                    self.excluded,
                    self.orig
                ),
            );
        }
        for s in &self.steps {
            b.push_str(&format!(
                "- `{}` {}: {}\n",
                s.id,
                s.action.as_str(),
                s.detail
            ));
        }
        let list = build_checklist(&self.raw, &[]);
        if !list.is_empty() {
            b.push_str("\n## Left for a human\n");
            for e in &list {
                b.push_str(&format!("- [{}] {}", e.device, e.title));
                if !e.command.is_empty() {
                    b.push_str(&format!(" (`{}`)", e.command));
                }
                b.push('\n');
            }
        }
        b.push_str(BODY_TAIL);
        b
    }

    fn push_step(&mut self, id: &str, r: Res) -> bool {
        let (action, detail, ok) = match r {
            Ok((a, d)) => (a, d, true),
            Err(d) => (MAction::Failed, d, false),
        };
        self.steps.push(MStep {
            id: id.into(),
            action,
            detail,
        });
        ok
    }

    /// Undo this run's commits: the worktree goes back to where the steps started (the base, or
    /// the resumed branch's tip). The user's checkout is not involved.
    fn rollback(&self) -> Result<(), String> {
        let o = self.git(&["reset", "--hard", &self.start]);
        if o.code == 0 {
            Ok(())
        } else {
            Err(format!("git reset failed: {}", o.stderr.trim()))
        }
    }
}

/// `tool from -> to` lines of a bosun `changed`/`behind` array.
fn behind_list(v: &Value) -> String {
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|i| {
                    format!(
                        "{} {} -> {}",
                        i["tool"].as_str().unwrap_or("?"),
                        i["from"].as_str().unwrap_or("?"),
                        i["to"].as_str().unwrap_or("?")
                    )
                })
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default()
}

fn human_steps(v: &Value) -> Vec<HumanStep> {
    v["human_steps"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|h| {
                    Some(HumanStep {
                        id: h["id"].as_str()?.to_string(),
                        title: h["title"].as_str()?.to_string(),
                        url: h["url"].as_str().unwrap_or("").to_string(),
                        command: String::new(),
                    })
                })
                .collect()
        })
        .unwrap_or_default()
}

/// Is the local migration branch spent? Merged into the base, or the same tree as the base (a
/// squash merge), or its PR is merged on GitHub (asked only when `gh` works) with the branch at
/// the PR's head.
fn leftover(
    git: &dyn Fn(&[&str]) -> Out,
    r: &dyn Runner,
    dir: &Path,
    branch: &str,
    base: &str,
) -> Result<bool, String> {
    if git(&["merge-base", "--is-ancestor", branch, base]).code == 0 {
        return Ok(true);
    }
    let tree = |rev: &str| {
        let o = git(&["rev-parse", &format!("{rev}^{{tree}}")]);
        (o.code == 0).then(|| o.stdout.trim().to_string())
    };
    if tree(branch).is_some() && tree(branch) == tree(base) {
        return Ok(true);
    }
    let c = Cmd::new("gh", &["repo", "view", "--json", "nameWithOwner"]).dir(dir);
    let o = r.run(&c);
    let repo = json(&o)
        .and_then(|v| v["nameWithOwner"].as_str().map(String::from))
        .filter(|_| o.code == 0);
    let Some(pr) = repo.and_then(|repo| gh::pr_view(r, dir, &repo, branch)) else {
        return Ok(false);
    };
    if pr.state != "MERGED" {
        return Ok(false);
    }
    let tip = git(&["rev-parse", branch]).stdout.trim().to_string();
    if !pr.head.is_empty() && pr.head == tip {
        return Ok(true);
    }
    Err(format!(
        "branch {branch} has commits beyond the head of its merged PR {} (PR head {}, branch at {tip})",
        pr.url,
        if pr.head.is_empty() {
            "unknown"
        } else {
            &pr.head
        }
    ))
}

/// The branch origin calls its default: `git ls-remote --symref origin HEAD`, else the local
/// `origin/HEAD`.
fn origin_default(git: &dyn Fn(&[&str]) -> Out) -> Option<String> {
    let o = git(&["ls-remote", "--symref", "origin", "HEAD"]);
    let from_remote = (o.code == 0)
        .then(|| {
            o.stdout.lines().find_map(|l| {
                l.strip_prefix("ref: refs/heads/")
                    .and_then(|r| r.split_whitespace().next())
                    .map(String::from)
            })
        })
        .flatten();
    from_remote.or_else(|| {
        let h = git(&["symbolic-ref", "--short", "refs/remotes/origin/HEAD"]);
        (h.code == 0)
            .then(|| h.stdout.trim().strip_prefix("origin/").map(String::from))
            .flatten()
    })
}

/// An environment error (exit 3) whose message says how to fix it.
fn env_err(msg: impl Into<String>, fix: impl Into<String>) -> KeelError {
    KeelError::Env(format!("{}; fix: {}", msg.into(), fix.into()))
}

/// Resolve the base ref: `--base REF` as given, else `origin/<default>` after a fetch that must
/// succeed (no stale base).
fn resolve_base(git: &dyn Fn(&[&str]) -> Out, explicit: Option<&str>) -> Result<String, KeelError> {
    if let Some(b) = explicit {
        let ok = git(&[
            "rev-parse",
            "--verify",
            "--quiet",
            &format!("{b}^{{commit}}"),
        ]);
        if ok.code != 0 {
            return Err(env_err(
                format!("--base {b}: no such commit"),
                "pass a branch, tag or sha that exists locally (fetch it first)",
            ));
        }
        return Ok(b.to_string());
    }
    let Some(name) = origin_default(git) else {
        return Err(env_err(
            "cannot find the default branch of `origin` (no network, or no origin remote)",
            "fix the remote (`git remote -v`) or the network, or pass --base REF",
        ));
    };
    let f = git(&["fetch", "origin", &name]);
    if f.code != 0 {
        return Err(env_err(
            format!(
                "cannot fetch origin/{name}: {}; a stale base would migrate old files",
                f.stderr.trim()
            ),
            "fix the network or credentials and rerun, or pass --base REF",
        ));
    }
    let base = format!("origin/{name}");
    if git(&[
        "rev-parse",
        "--verify",
        "--quiet",
        &format!("{base}^{{commit}}"),
    ])
    .code
        != 0
    {
        return Err(env_err(
            format!("{base} is missing after the fetch"),
            "check `git remote -v`, or pass --base REF",
        ));
    }
    Ok(base)
}

/// `<git-common-dir>` as an absolute path (shared by every worktree of the repo).
fn common_dir(git: &dyn Fn(&[&str]) -> Out, dir: &Path) -> Option<PathBuf> {
    let o = git(&["rev-parse", "--git-common-dir"]);
    let t = o.stdout.trim();
    if o.code != 0 || t.is_empty() {
        return None;
    }
    let p = Path::new(t);
    let abs = if p.is_absolute() {
        p.to_path_buf()
    } else {
        dir.join(p)
    };
    Some(abs.canonicalize().unwrap_or(abs))
}

pub fn run(dir: &Path, args: &MigrateArgs, r: &dyn Runner) -> Result<MigrateReport, KeelError> {
    let target = args
        .to
        .clone()
        .unwrap_or_else(|| env!("CARGO_PKG_VERSION").to_string());
    if !valid_semver(&target) {
        return Err(KeelError::Fix {
            message: format!("--to {target:?} is not a release number"),
            fix: "keel migrate --to 0.23.0".into(),
        });
    }
    // The user's checkout is only read (and `git fetch` updates a remote-tracking ref): every
    // write happens in a temporary worktree of the same repository.
    let gitc = |a: &[&str]| r.run(&Cmd::new("git", a).dir(dir));
    if gitc(&["rev-parse", "--is-inside-work-tree"]).code != 0 {
        return Err(env_err(
            "not a git checkout",
            "run keel migrate inside the repo's clone",
        ));
    }
    let Some(common) = common_dir(&gitc, dir) else {
        return Err(env_err(
            "cannot find the git directory",
            "run `git rev-parse --git-common-dir`",
        ));
    };
    let top = gitc(&["rev-parse", "--show-toplevel"])
        .stdout
        .trim()
        .to_string();
    let repo_name = Path::new(&top)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let orig = gitc(&["rev-parse", "--abbrev-ref", "HEAD"])
        .stdout
        .trim()
        .to_string();
    let orig = if orig.is_empty() {
        "HEAD".to_string()
    } else {
        orig
    };
    let custom = args.branch.is_some();
    let branch = args
        .branch
        .clone()
        .unwrap_or_else(|| format!("keel/migrate-v{target}"));
    if !custom && orig == branch {
        return Err(env_err(
            format!("you are on {branch}, the branch keel works on in its own worktree"),
            "switch to another branch (`git switch main`) and rerun; the work on it is picked up",
        ));
    }
    if args.pr && !args.dry_run {
        match gh::auth_ok(r) {
            None => {
                return Err(env_err(
                    "gh not found; --pr needs the GitHub CLI",
                    "install gh (https://cli.github.com) or run without --pr",
                ));
            }
            Some(false) => {
                return Err(env_err("gh is not logged in", "run `gh auth login`"));
            }
            Some(true) => {}
        }
    }
    let base = resolve_base(&gitc, args.base.as_deref())?;
    let excluded = gitc(&["rev-list", "--count", &format!("{base}..HEAD")])
        .stdout
        .trim()
        .parse()
        .unwrap_or(0);

    // The worktree: under the git dir, so nothing appears in the user's checkout.
    let keel_dir = common.join("keel");
    let wt = keel_dir.join(format!("migrate-v{target}"));
    let _ = std::fs::create_dir_all(&keel_dir);
    if wt.exists() {
        // A crashed earlier run left it behind.
        let _ = gitc(&["worktree", "remove", "--force", &wt.display().to_string()]);
        let _ = std::fs::remove_dir_all(&wt);
    }
    let _ = gitc(&["worktree", "prune"]);
    let exists = gitc(&[
        "rev-parse",
        "--verify",
        "--quiet",
        &format!("refs/heads/{branch}"),
    ])
    .code
        == 0;
    let mut created = false;
    let wts = wt.display().to_string();
    let add = if args.dry_run {
        gitc(&["worktree", "add", "--detach", &wts, &base])
    } else if custom {
        // Detached at the branch's tip (local, else origin's, else the base): the checkout may
        // have the branch checked out. The push goes to the branch by name.
        let start = crate::tools::git::branch_start(r, dir, &branch, &base);
        gitc(&["worktree", "add", "--detach", &wts, &start])
    } else if exists {
        let spent = leftover(&gitc, r, dir, &branch, &base).map_err(|e| {
            env_err(
                e,
                format!("`git log {branch} --not {base}` shows them; keep them (`git switch {branch}`) or `git branch -D {branch}` once sure"),
            )
        })?;
        if spent {
            // An earlier migration PR landed (fast-forward, squash or merged on GitHub): the
            // branch is only a leftover.
            let _ = gitc(&["branch", "-D", &branch]);
            created = true;
            gitc(&["worktree", "add", "-b", &branch, &wts, &base])
        } else {
            if gitc(&["merge-base", "--is-ancestor", &base, &branch]).code != 0 {
                return Err(env_err(
                    format!("branch {branch} is behind {base} and not merged"),
                    format!("`git branch -D {branch}` to start over, or rebase it onto {base}"),
                ));
            }
            gitc(&["worktree", "add", &wts, &branch])
        }
    } else {
        created = true;
        gitc(&["worktree", "add", "-b", &branch, &wts, &base])
    };
    if add.code != 0 {
        return Err(KeelError::Env(format!(
            "cannot create the worktree {wts}: {}; fix: `git worktree prune`, then rerun",
            add.stderr.trim()
        )));
    }
    let report = in_worktree(
        r, &wt, &keel_dir, args, &target, &branch, &base, &orig, &repo_name, excluded, created,
    );
    // Always: the worktree goes; a branch keel created for nothing goes with it.
    let _ = gitc(&["worktree", "remove", "--force", &wts]);
    let _ = std::fs::remove_dir_all(&wt);
    let _ = gitc(&["worktree", "prune"]);
    if created && report.as_ref().map_or(true, |r| r.branch.is_none()) {
        let _ = gitc(&["branch", "-D", &branch]);
    }
    report
}

#[allow(clippy::too_many_arguments)]
fn in_worktree(
    r: &dyn Runner,
    wt: &Path,
    keel_dir: &Path,
    args: &MigrateArgs,
    target: &str,
    branch: &str,
    base: &str,
    orig: &str,
    repo_name: &str,
    excluded: u32,
    created: bool,
) -> Result<MigrateReport, KeelError> {
    let target = target.to_string();
    let branch = branch.to_string();
    let p = detect(wt);
    if !(p.splice || p.bosun || p.hoist) {
        return Err(env_err(
            format!("nothing to migrate: no .splice/, .bosun/ or hoist.toml on {base}"),
            "pass --base REF if the pieces live on another branch, or `keel up` to bootstrap a repo",
        ));
    }
    let start = r
        .run(&Cmd::new("git", &["rev-parse", "HEAD"]).dir(wt))
        .stdout
        .trim()
        .to_string();
    let dry = args.dry_run;
    let mut m = Mig {
        r,
        dir: wt.to_path_buf(),
        target: target.clone(),
        dry,
        args: args.clone(),
        pins: Pins::load(wt)?,
        p: p.clone(),
        steps: Vec::new(),
        raw: Vec::new(),
        branch: branch.clone(),
        orig: orig.to_string(),
        start: start.clone(),
        base: base.to_string(),
        excluded,
        keel_dir: keel_dir.to_path_buf(),
        repo_name: repo_name.to_string(),
        snippet: Snippet {
            status: "not-checked",
            path: None,
            sha256: None,
            summary: String::new(),
        },
        before: None,
        pr: None,
        base_drift: Vec::new(),
        not_updated: Vec::new(),
        notes: Vec::new(),
        fetched: std::collections::HashMap::new(),
        cache: None,
    };
    if !dry && p.bosun {
        // The old snippet: the one kept from an earlier failed run, else what the installed bosun prints.
        let kept = keel_dir.join(SNIPPET_BEFORE);
        m.before = std::fs::read_to_string(&kept)
            .ok()
            .or_else(|| m.snippet_now());
        if let Some(b) = &m.before {
            let _ = std::fs::create_dir_all(keel_dir);
            let _ = std::fs::write(&kept, b);
        }
    }

    let order = [
        "tools",
        "splice",
        "bosun-pin",
        "hoist",
        "setup-snippet",
        "verify",
        "mode",
        "pr",
    ];
    let mut failed: Option<usize> = None;
    for (i, id) in order.iter().enumerate() {
        if failed.is_some() {
            m.steps.push(MStep {
                id: (*id).into(),
                action: MAction::NotReached,
                detail: String::new(),
            });
            continue;
        }
        if *id == "pr" && (m.dry || m.ahead() == 0) {
            m.steps.push(MStep {
                id: "pr".into(),
                action: MAction::Skipped,
                detail: if m.dry {
                    "dry-run: no push, no PR".into()
                } else {
                    "nothing changed: no PR".into()
                },
            });
            continue;
        }
        if *id == "splice" && p.splice {
            m.baseline();
        }
        let res = match *id {
            "tools" => m.s_tools(),
            "splice" => m.s_splice(),
            "bosun-pin" => m.s_bosun_pin(),
            "hoist" => m.s_hoist(),
            "setup-snippet" => m.s_snippet(),
            "verify" => m.s_verify(),
            "mode" => m.s_mode(),
            _ => m.s_pr(),
        };
        if !m.push_step(id, res) {
            failed = Some(i);
        }
    }

    let mut recovery = None;
    let mut keep_branch = !m.dry;
    if let Some(i) = failed {
        let fid = order[i];
        if fid == "pr" {
            // The migration is committed and fine; only the push or PR failed.
            recovery = Some(format!(
                "the migration is committed on branch {branch} (nothing lost); fix the push or `gh` problem above, then rerun `keel migrate --pr`"
            ));
        } else if m.dry {
            recovery = Some("nothing was written; fix the problem above and rerun".into());
        } else {
            let undone = m.rollback();
            recovery = Some(match undone {
                Ok(()) => format!(
                    "rolled back: your checkout and branch {orig} were never touched{}; tools installed by npm stay installed. Fix step `{fid}` (see its detail), then rerun `keel migrate`",
                    if created {
                        format!(", and the work branch {branch} is deleted")
                    } else {
                        format!(", and {branch} is back at {start}")
                    }
                ),
                Err(e) => format!(
                    "rollback failed ({e}); run `git branch -D {branch}` (or `git branch -f {branch} {start}` when it existed before) by hand. Then fix step `{fid}` and rerun `keel migrate`"
                ),
            });
            keep_branch = false;
        }
    }

    let changed = failed.is_none() && !m.dry && m.ahead() > 0;
    if failed.is_none() && !m.dry {
        let _ = std::fs::remove_file(keel_dir.join(SNIPPET_BEFORE));
        if !changed {
            keep_branch = false;
        }
    }
    if failed.is_none() && changed {
        match (&m.pr, m.args.pr) {
            (Some(pr), _) => {
                let (url, msg) = (
                    pr.url.clone(),
                    format!("Approve and merge the migration PR {}", pr.url),
                );
                m.human("approve-pr", msg, &url, "");
            }
            (None, false) => m.human(
                "open-pr",
                format!("Push {branch} and open the PR (keel never merges it)"),
                "",
                "keel migrate --pr",
            ),
            _ => {}
        }
    }

    let checklist = build_checklist(&m.raw, &[]);
    let human_step = checklist.first().map(|e| HumanStep {
        id: e.id.clone(),
        title: e.title.clone(),
        url: e.url.clone(),
        command: e.command.clone(),
    });
    let would_run = m.steps.iter().any(|s| s.action == MAction::WouldRun);
    let (status, exit_code) = if failed.is_some() {
        ("failed", 1)
    } else if m.dry && would_run {
        ("planned", 1)
    } else if human_step.is_some() {
        ("human", 5)
    } else {
        ("done", 0)
    };
    Ok(MigrateReport {
        command: "migrate",
        status,
        exit_code,
        target,
        dry_run: m.dry,
        from_branch: orig.to_string(),
        branch: keep_branch.then_some(branch),
        base: Some(base.to_string()),
        excluded_commits: m.excluded,
        pieces: p,
        steps: m.steps,
        changed,
        pr: m.pr,
        setup_snippet: m.snippet,
        checklist,
        human_step,
        recovery,
        notes: m.notes,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_refusal_with_broken_markers_is_not_old_drift() {
        let drift = "channel c: `a.md` is owned by channel c but was edited locally";
        let ok = serde_json::json!({"messages": [drift, "nothing was written; revert"]});
        assert_eq!(refusal_paths(&ok), Some(vec!["a.md".to_string()]));
        let mixed = serde_json::json!({"messages": [
            drift,
            "channel c: AGENTS.md: unbalanced splice:c marker at line 1; restore it",
            "nothing was written; revert"
        ]});
        assert_eq!(refusal_paths(&mixed), None);
        let none = serde_json::json!({"messages": ["nothing was written"]});
        assert_eq!(refusal_paths(&none), None);
    }

    #[test]
    fn release_numbers_are_x_y_z() {
        assert!(valid_semver("0.23.0"));
        for bad in [
            "",
            "1",
            "1.2",
            "1.2.3.4",
            "v1.2.3",
            "1.2.x",
            "1..3",
            "1.2.3-rc1",
        ] {
            assert!(!valid_semver(bad), "{bad}");
        }
    }

    #[test]
    fn version_is_the_last_word_without_v() {
        assert_eq!(
            version_of(&Out::ok("splice 0.23.0\n")).as_deref(),
            Some("0.23.0")
        );
        assert_eq!(version_of(&Out::ok("v0.23.0")).as_deref(), Some("0.23.0"));
        assert_eq!(version_of(&Out::with(1, "0.23.0", "")), None);
        assert_eq!(version_of(&Out::with(-1, "", "")), None);
    }

    #[test]
    fn snippet_summary_counts_lines_and_names_the_diff() {
        let s = snippet_summary("a\nb\nc\n", "a\nb\nd\ne\n", Path::new("/g/keel"));
        assert!(s.starts_with("2 lines added, 1 removed (sha256 "), "{s}");
        assert!(s.contains("diff /g/keel/cloud-setup.previous.sh /g/keel/cloud-setup.sh"));
    }

    #[test]
    fn detect_finds_only_what_is_on_disk() {
        let d = tempfile::tempdir().unwrap();
        let p = detect(d.path());
        assert!(!p.splice && !p.bosun && !p.hoist && !p.keel);
        std::fs::create_dir_all(d.path().join(".splice/channels")).unwrap();
        std::fs::write(d.path().join(".splice/channels/decisions.toml"), "").unwrap();
        std::fs::create_dir_all(d.path().join(".bosun")).unwrap();
        let p = detect(d.path());
        assert!(p.splice && p.bosun && p.decisions_channel && !p.bosun_channel && !p.hoist);
    }

    #[test]
    fn behind_list_reads_bosun_pin_json() {
        let v: Value =
            serde_json::from_str(r#"[{"tool":"bosun","from":"0.22.1","to":"0.23.0"}]"#).unwrap();
        assert_eq!(behind_list(&v), "bosun 0.22.1 -> 0.23.0");
        assert_eq!(behind_list(&Value::Null), "");
    }

    #[test]
    fn a_bad_target_is_a_usage_error() {
        let d = tempfile::tempdir().unwrap();
        let a = MigrateArgs {
            to: Some("latest".into()),
            ..MigrateArgs::default()
        };
        let e = run(d.path(), &a, &crate::exec::FakeRunner::new()).unwrap_err();
        assert_eq!(e.exit_code(), 2);
    }

    #[test]
    fn no_piece_is_an_environment_error_with_a_fix() {
        let d = tempfile::tempdir().unwrap();
        let e = run(
            d.path(),
            &MigrateArgs::default(),
            &crate::exec::FakeRunner::new(),
        )
        .unwrap_err();
        assert_eq!(e.exit_code(), 3);
    }

    #[test]
    fn registry_pin_reads_dist_integrity_of_both_packages() {
        let r = crate::exec::FakeRunner::new().on(&["npm", "view"], Out::ok("sha512-QUJD\n"));
        let pin = npm::registry_pin(&r, Path::new("."), "splice", "0.23.0").unwrap();
        let s = pin.sha512.unwrap();
        assert_eq!(s.launcher, "QUJD");
        assert_eq!(s.platform.values().next().unwrap(), "QUJD");
        let calls = r.calls();
        assert!(calls[0].line().contains("@keelstackhq/splice@0.23.0"));
        assert!(calls[1].line().contains("@keelstackhq/splice-"));
        let none = crate::exec::FakeRunner::new().on(&["npm", "view"], Out::with(1, "", "E404"));
        assert!(npm::registry_pin(&none, Path::new("."), "splice", "9.9.9").is_err());
    }
}
