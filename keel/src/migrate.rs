//! `keel migrate` (spec §11): move an existing repo to a keelstack release in one command.
//!
//! One branch, one commit per step, verification, optionally one PR. The steps call the tools
//! (npm, splice, bosun, hoist, git, gh) as subprocesses and read their JSON; keel never
//! reimplements them. Any failure rolls the work back so the original branch is untouched.
use crate::cli::MigrateArgs;
use crate::error::KeelError;
use crate::exec::{Cmd, Out, Runner};
use crate::pins::{Pins, ToolPin};
use crate::report::{ChecklistEntry, HumanStep, build_checklist};
use crate::steps::agent_env;
use crate::tools::{self, failure, gh, hoist, json, npm};
use serde::Serialize;
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use std::time::Duration;

const SNIPPET_FILE: &str = agent_env::FILE;
const SNIPPET_PREV: &str = ".keel/cloud-setup.previous.sh";
const SNIPPET_BEFORE: &str = ".keel/migrate-snippet-before";
const TOOL_TIMEOUT: Duration = Duration::from_secs(600);
const BODY_TAIL: &str = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
/// `git status` pathspec: keel's own scratch directory never counts as a change.
const NOT_KEEL: [&str; 3] = ["--", ".", ":(exclude).keel"];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum MAction {
    Ok,
    Done,
    WouldRun,
    Skipped,
    Pending,
    Failed,
    NotReached,
}

impl MAction {
    fn as_str(self) -> &'static str {
        match self {
            MAction::Ok => "ok",
            MAction::Done => "done",
            MAction::WouldRun => "would-run",
            MAction::Skipped => "skipped",
            MAction::Pending => "pending",
            MAction::Failed => "failed",
            MAction::NotReached => "not-reached",
        }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct MStep {
    pub id: String,
    pub action: MAction,
    pub detail: String,
}

/// Which keelstack pieces the repo uses (found on disk; absent ones are skipped).
#[derive(Debug, Clone, Default, Serialize)]
pub struct Pieces {
    pub splice: bool,
    pub bosun: bool,
    pub hoist: bool,
    pub keel: bool,
    pub setup_script: bool,
    #[serde(skip)]
    decisions_channel: bool,
    #[serde(skip)]
    bosun_channel: bool,
}

fn detect(dir: &Path) -> Pieces {
    let ch = dir.join(".splice/channels");
    let channels = std::fs::read_dir(&ch).is_ok_and(|d| {
        d.flatten()
            .any(|e| e.path().extension().is_some_and(|x| x == "toml"))
    });
    Pieces {
        splice: dir.join(".splice/lock.toml").is_file() || channels,
        bosun: dir.join(".bosun").is_dir(),
        hoist: dir.join("hoist.toml").is_file(),
        keel: dir.join("keel.toml").is_file(),
        setup_script: dir.join("docs/setup-script.sh").is_file(),
        decisions_channel: ch.join("decisions.toml").is_file(),
        bosun_channel: ch.join("bosun.toml").is_file(),
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct PrInfo {
    /// `opened` (keel made it now) or `existing`.
    pub action: &'static str,
    pub url: String,
}

/// The cloud-environment setup snippet: pasted once by a human, only needed again when bosun's
/// bootstrap text changed between the old and the new release.
#[derive(Debug, Clone, Serialize)]
pub struct Snippet {
    /// `changed` | `unchanged` | `unknown` (no old bosun to compare with: paste to be safe) | `not-checked`.
    pub status: &'static str,
    pub path: Option<String>,
    pub sha256: Option<String>,
    pub summary: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct MigrateReport {
    pub command: &'static str,
    pub status: &'static str,
    pub exit_code: i32,
    pub target: String,
    pub dry_run: bool,
    /// The branch the user was on when keel started.
    pub from_branch: String,
    /// The migration branch the work is on now; None when nothing changed (or `--dry-run`).
    pub branch: Option<String>,
    pub pieces: Pieces,
    pub steps: Vec<MStep>,
    pub changed: bool,
    pub pr: Option<PrInfo>,
    pub setup_snippet: Snippet,
    pub checklist: Vec<ChecklistEntry>,
    pub human_step: Option<HumanStep>,
    /// On failure: what was rolled back and the exact commands to recover.
    pub recovery: Option<String>,
}

#[derive(Serialize)]
struct JsonView<'a> {
    version: u32,
    ok: bool,
    #[serde(flatten)]
    report: &'a MigrateReport,
}

pub fn render_migrate_json(r: &MigrateReport) -> String {
    serde_json::to_string(&JsonView {
        version: 1,
        ok: r.exit_code == 0,
        report: r,
    })
    .expect("report serializes")
}

pub fn render_migrate_text(r: &MigrateReport) -> String {
    let mut out = String::new();
    for s in &r.steps {
        out.push_str(&format!(
            "{:<14} {:<11} {}\n",
            s.id,
            s.action.as_str(),
            s.detail
        ));
    }
    if let Some(b) = &r.branch {
        out.push_str(&format!("\nbranch: {b} (from {})\n", r.from_branch));
    }
    if let Some(p) = &r.pr {
        out.push_str(&format!("pr: {} ({})\n", p.url, p.action));
    }
    if let Some(rec) = &r.recovery {
        out.push_str(&format!("\nrecovery: {rec}\n"));
    }
    if !r.checklist.is_empty() {
        out.push_str("\nchecklist:\n");
        for (i, e) in r.checklist.iter().enumerate() {
            let mut line = format!("  {}. [{}] {}", i + 1, e.device, e.title);
            for extra in [&e.url, &e.command] {
                if !extra.is_empty() {
                    line.push_str(" | ");
                    line.push_str(extra);
                }
            }
            out.push_str(&line);
            out.push('\n');
        }
    } else if r.status == "done" {
        out.push_str(if r.changed || r.dry_run {
            "\ndone\n"
        } else {
            "\nup to date: nothing to change\n"
        });
    }
    out
}

/// `X.Y.Z`, three numbers.
fn valid_semver(v: &str) -> bool {
    let p: Vec<&str> = v.split('.').collect();
    p.len() == 3
        && p.iter()
            .all(|n| !n.is_empty() && n.len() < 10 && n.bytes().all(|b| b.is_ascii_digit()))
}

fn sha256_hex(s: &str) -> String {
    Sha256::digest(s.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// `a lines added, b removed` between two scripts (as sets of lines), with short hashes.
fn snippet_summary(old: &str, new: &str) -> String {
    let (o, n): (Vec<&str>, Vec<&str>) = (old.lines().collect(), new.lines().collect());
    let added = n.iter().filter(|l| !o.contains(l)).count();
    let removed = o.iter().filter(|l| !n.contains(l)).count();
    format!(
        "{added} lines added, {removed} removed (sha256 {} -> {}); compare with `diff {SNIPPET_PREV} {SNIPPET_FILE}`",
        &sha256_hex(old)[..12],
        &sha256_hex(new)[..12]
    )
}

/// The last word of the first line of `<tool> --version`, without a leading `v`.
fn version_of(o: &Out) -> Option<String> {
    if o.code != 0 {
        return None;
    }
    let tok = o.stdout.lines().next()?.split_whitespace().last()?;
    Some(tok.strip_prefix('v').unwrap_or(tok).to_string())
}

type Res = Result<(MAction, String), String>;

struct Mig<'a> {
    r: &'a dyn Runner,
    dir: PathBuf,
    target: String,
    dry: bool,
    args: MigrateArgs,
    p: Pieces,
    pins: Pins,
    steps: Vec<MStep>,
    raw: Vec<HumanStep>,
    branch: String,
    orig: String,
    /// Commits keel made in this run.
    commits: u32,
    snippet: Snippet,
    before: Option<String>,
    pr: Option<PrInfo>,
}

impl Mig<'_> {
    fn tool(&self, prog: &str, args: &[&str]) -> Cmd {
        Cmd::new(prog, args).dir(&self.dir).timeout(TOOL_TIMEOUT)
    }

    fn git(&self, args: &[&str]) -> Out {
        self.r.run(&Cmd::new("git", args).dir(&self.dir))
    }

    fn human(&mut self, id: &str, title: String, url: &str, command: &str) {
        self.raw.push(HumanStep {
            id: id.into(),
            title,
            url: url.into(),
            command: command.into(),
        });
    }

    /// Stage everything but `.keel/` and commit it; false when there was nothing to commit.
    fn commit_all(&mut self, message: &str) -> Result<bool, String> {
        let add = Cmd::new("git", &["add", "-A"]).dir(&self.dir);
        let o = self.r.run(&add);
        if o.code != 0 {
            return Err(failure(&add, &o));
        }
        // Belt and braces: `.keel/` is in .git/info/exclude, but never commit it.
        let _ = self.git(&[
            "rm",
            "-r",
            "--cached",
            "-q",
            "--ignore-unmatch",
            "--",
            ".keel",
        ]);
        let quiet = self.git(&["diff", "--cached", "--quiet"]);
        if quiet.code == 0 {
            return Ok(false);
        }
        let c = Cmd::new("git", &["commit", "-m", message]).dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        self.commits += 1;
        Ok(true)
    }

    fn s_tools(&mut self) -> Res {
        let wanted: Vec<&str> = [
            ("splice", self.p.splice),
            ("bosun", self.p.bosun),
            ("hoist", self.p.hoist),
        ]
        .iter()
        .filter(|(_, used)| *used)
        .map(|(t, _)| *t)
        .collect();
        if wanted.is_empty() {
            return Ok((MAction::Skipped, "no tool in use".into()));
        }
        let (mut notes, mut todo) = (Vec::new(), 0);
        for t in wanted {
            let have = version_of(&self.r.run(&Cmd::new(t, &["--version"])));
            if have.as_deref() == Some(self.target.as_str()) {
                notes.push(format!("{t} {}", self.target));
                continue;
            }
            let from = have.unwrap_or_else(|| "none".into());
            if self.dry {
                todo += 1;
                notes.push(format!("{t} {from} -> {}", self.target));
                continue;
            }
            let pin = self.pin_of(t)?;
            npm::install_pinned(self.r, t, &pin)?;
            notes.push(format!("{t} {from} -> {}", self.target));
        }
        let action = match (todo, self.dry) {
            (0, false) if notes.iter().all(|n| !n.contains("->")) => MAction::Ok,
            (0, _) => MAction::Done,
            _ => MAction::WouldRun,
        };
        Ok((action, notes.join(", ")))
    }

    /// keel's embedded sha512 when it has them for exactly this version, else the registry's.
    fn pin_of(&self, tool: &str) -> Result<ToolPin, String> {
        if let Some(p) = self.pins.tool(tool)
            && p.version == self.target
            && p.sha512.is_some()
        {
            return Ok(p);
        }
        npm::registry_pin(self.r, tool, &self.target)
    }

    fn splice_update(&self, extra: &[&str]) -> Result<String, String> {
        let mut a = vec!["--json", "--yes", "update"];
        a.extend(extra);
        let c = self.tool("splice", &a);
        let o = self.r.run(&c);
        match o.code {
            0 => {
                let n = json(&o)
                    .and_then(|v| v["changes"].as_array().map(|a| a.len()))
                    .unwrap_or(0);
                Ok(format!("{n} file changes"))
            }
            1 => Err(format!(
                "{}; conflicts or edited owned files need a decision: run `splice update {}` by hand, \
                 resolve them, then rerun keel migrate",
                failure(&c, &o),
                extra.join(" ")
            )),
            _ => Err(failure(&c, &o)),
        }
    }

    fn s_splice(&mut self) -> Res {
        if !self.p.splice {
            return Ok((MAction::Skipped, "no .splice/lock.toml or channel".into()));
        }
        if self.dry {
            let c = self.tool("splice", &["--json", "check"]);
            let o = self.r.run(&c);
            return match o.code {
                0 => Ok((MAction::Ok, "up to date".into())),
                1 => Ok((
                    MAction::WouldRun,
                    "an update, drift or markers (`splice check` exits 1); `splice diff` shows them"
                        .into(),
                )),
                _ => Err(failure(&c, &o)),
            };
        }
        let mut notes = Vec::new();
        if self.p.decisions_channel {
            let d = self.splice_update(&["--channel", "decisions"])?;
            if self.commit_all("chore: sync org decisions")? {
                notes.push(format!("decisions channel ({d})"));
            }
        }
        let d = self.splice_update(&["--all"])?;
        if self.commit_all("chore: splice update to the latest template and channels")? {
            notes.push(format!("template and channels ({d})"));
        }
        if notes.is_empty() {
            Ok((MAction::Ok, "up to date".into()))
        } else {
            Ok((MAction::Done, notes.join(", ")))
        }
    }

    fn pin_file_version(&self) -> Option<String> {
        std::fs::read_to_string(self.dir.join(".bosun/version"))
            .ok()
            .map(|s| s.trim().to_string())
    }

    fn s_bosun_pin(&mut self) -> Res {
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        if self.p.bosun_channel {
            return Ok((
                MAction::Skipped,
                "the bosun channel owns the pins; `splice update` moved them".into(),
            ));
        }
        if !self.p.setup_script {
            return Ok((MAction::Skipped, "no docs/setup-script.sh to pin".into()));
        }
        if self.dry {
            let c = self.tool("bosun", &["--json", "pin", "--latest", "--check"]);
            let o = self.r.run(&c);
            if o.code != 0 {
                return Err(failure(&c, &o));
            }
            let behind = json(&o)
                .map(|v| behind_list(&v["data"]["behind"]))
                .unwrap_or_default();
            return Ok(if behind.is_empty() {
                (MAction::Ok, "pins are at npm latest".into())
            } else {
                (MAction::WouldRun, behind)
            });
        }
        let c = self.tool("bosun", &["--json", "pin", "--latest"]);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        let v = json(&o).ok_or_else(|| tools::not_json(&c))?;
        let changed = behind_list(&v["data"]["changed"]);
        if let Some(have) = self.pin_file_version()
            && have != self.target
        {
            return Err(format!(
                "`bosun pin --latest` leaves .bosun/version at {have}, not the target {}: bosun pins only \
                 move to npm latest, so pass `--to {have}` (or wait until {} is npm latest)",
                self.target, self.target
            ));
        }
        if self.commit_all(&format!("chore: pin keelstack tools to {}", self.target))? {
            Ok((MAction::Done, changed))
        } else {
            Ok((MAction::Ok, "pins already current".into()))
        }
    }

    fn s_hoist(&mut self) -> Res {
        if !self.p.hoist {
            return Ok((MAction::Skipped, "no hoist.toml".into()));
        }
        if !self.dir.join(".github/workflows/release.yml").is_file() {
            return Ok((MAction::Skipped, "no release workflow to refresh".into()));
        }
        let mut a = vec!["--json", "init"];
        if self.dry {
            a.push("--dry-run");
        }
        let c = self.tool("hoist", &a);
        let o = self.r.run(&c);
        match o.code {
            0 | 1 => {
                if self.dry {
                    let n = json(&o)
                        .map(|v| {
                            v["items"]
                                .as_array()
                                .map(|a| {
                                    a.iter()
                                        .filter(|i| {
                                            matches!(
                                                i["action"].as_str(),
                                                Some("create" | "update")
                                            )
                                        })
                                        .count()
                                })
                                .unwrap_or(0)
                        })
                        .unwrap_or(0);
                    return Ok(if n == 0 {
                        (MAction::Ok, "release.yml is current".into())
                    } else {
                        (
                            MAction::WouldRun,
                            format!("hoist init would rewrite {n} file(s)"),
                        )
                    });
                }
                if self.commit_all("chore: refresh the hoist release workflow")? {
                    Ok((MAction::Done, "release.yml refreshed by hoist init".into()))
                } else {
                    Ok((MAction::Ok, "release.yml is current".into()))
                }
            }
            2 => {
                // Own release workflow left alone is not a task; anything else is.
                let steps = json(&o).map(|v| human_steps(&v)).unwrap_or_default();
                let open: Vec<HumanStep> = steps
                    .into_iter()
                    .filter(|h| !h.id.starts_with("release-workflow"))
                    .collect();
                let n = open.len();
                self.raw.extend(open);
                Ok((
                    if n == 0 {
                        MAction::Ok
                    } else {
                        MAction::Pending
                    },
                    if n == 0 {
                        "release.yml is yours, left alone".into()
                    } else {
                        format!("{n} human step(s) from hoist init")
                    },
                ))
            }
            _ => {
                // hoist init looks up its release tag on GitHub: offline or without a token it
                // cannot run. That must not block the migration, but it must not vanish either.
                self.human(
                    "hoist-init",
                    "Refresh the hoist release workflow (hoist init could not run here)".into(),
                    "",
                    "hoist init",
                );
                Ok((MAction::Skipped, failure(&c, &o)))
            }
        }
    }

    fn snippet_now(&self) -> Option<String> {
        let c = Cmd::new("bosun", &["--json", "setup-snippet"]).dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return None;
        }
        json(&o)?["data"]["script"]
            .as_str()
            .filter(|s| !s.trim().is_empty())
            .map(String::from)
    }

    fn s_snippet(&mut self) -> Res {
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        if self.dry {
            self.snippet = Snippet {
                status: "not-checked",
                path: None,
                sha256: None,
                summary: "compared after the real run".into(),
            };
            return Ok((
                MAction::Skipped,
                "dry-run: compared after the real run".into(),
            ));
        }
        let Some(after) = self.snippet_now() else {
            return Err(
                "`bosun --json setup-snippet` printed no data.script; upgrade bosun".into(),
            );
        };
        let sha = sha256_hex(&after);
        let (status, summary) = match &self.before {
            Some(b) if *b == after => ("unchanged", "the bootstrap text is the same".to_string()),
            Some(b) => ("changed", snippet_summary(b, &after)),
            None => (
                "unknown",
                "no earlier bosun to compare with; paste it to be safe".to_string(),
            ),
        };
        let mut path = None;
        if status != "unchanged" {
            let name = self
                .dir
                .canonicalize()
                .ok()
                .and_then(|d| d.file_name().map(|n| n.to_string_lossy().into_owned()))
                .unwrap_or_default();
            let write = |rel: &str, text: &str| -> Result<(), String> {
                let p = self.dir.join(rel);
                p.parent()
                    .map_or(Ok(()), std::fs::create_dir_all)
                    .and_then(|()| std::fs::write(&p, text))
                    .map_err(|e| format!("cannot write {rel}: {e}"))
            };
            write(SNIPPET_FILE, &agent_env::compose(&name, &after))?;
            if let Some(b) = &self.before {
                write(SNIPPET_PREV, &agent_env::compose(&name, b))?;
            }
            path = Some(SNIPPET_FILE.to_string());
            self.human(
                "setup-snippet",
                format!(
                    "Paste {SNIPPET_FILE} into the Setup script of your Claude Code cloud environment ({summary})"
                ),
                "https://claude.ai/code",
                &format!("cat {SNIPPET_FILE}"),
            );
        }
        self.snippet = Snippet {
            status,
            path,
            sha256: Some(sha),
            summary: summary.clone(),
        };
        Ok(if status == "unchanged" {
            (MAction::Ok, summary)
        } else {
            (MAction::Pending, format!("{status}: {summary}"))
        })
    }

    /// Read-only checks of the result: `splice check` must pass; `bosun doctor` and `hoist check`
    /// findings are remote state, so they become checklist entries instead of a rollback.
    fn s_verify(&mut self) -> Res {
        let mut notes = Vec::new();
        let mut pending = false;
        if self.p.splice {
            let c = self.tool("splice", &["--json", "check"]);
            let o = self.r.run(&c);
            // Dry-run reports the work `check` finds; the real run must end clean.
            if o.code != 0 && !self.dry {
                return Err(format!(
                    "splice check still fails after the update: {}",
                    failure(&c, &o)
                ));
            }
            notes.push(if o.code == 0 {
                "splice check ok".to_string()
            } else {
                "splice check: work left (dry-run)".to_string()
            });
        }
        if self.p.bosun {
            let c = self.tool("bosun", &["--json", "doctor"]);
            let o = self.r.run(&c);
            match o.code {
                0 => notes.push("bosun doctor ok".into()),
                5 => notes.push("bosun doctor skipped (no GITHUB_TOKEN)".into()),
                _ => {
                    let fix = json(&o)
                        .and_then(|v| {
                            v["data"]["next_step"]
                                .as_str()
                                .or_else(|| v["error"]["fix"].as_str())
                                .map(String::from)
                        })
                        .unwrap_or_else(|| failure(&c, &o));
                    self.human(
                        "bosun-doctor",
                        format!("bosun doctor reports work left: {fix}"),
                        "",
                        "bosun doctor",
                    );
                    notes.push("bosun doctor: work left".into());
                    pending = true;
                }
            }
        }
        if self.p.hoist {
            let c = self.tool("hoist", &["--json", "check"]);
            let o = self.r.run(&c);
            match o.code {
                0 => notes.push("hoist check ok".into()),
                1 => {
                    let drift = json(&o)
                        .map(|v| {
                            hoist::items_of(&v)
                                .into_iter()
                                .filter(|i| !matches!(i.action.as_str(), "ok" | "unknown"))
                                .take(3)
                                .map(|i| format!("{}/{}", i.kind, i.key))
                                .collect::<Vec<_>>()
                                .join(", ")
                        })
                        .unwrap_or_default();
                    self.human(
                        "hoist-apply",
                        format!(
                            "hoist reports drift ({drift}); apply it with an admin token (environments such as release-tags, reviewers, rulesets)"
                        ),
                        "",
                        "hoist apply --area github",
                    );
                    notes.push("hoist check: drift".into());
                    pending = true;
                }
                2 => {
                    let steps = json(&o).map(|v| human_steps(&v)).unwrap_or_default();
                    self.raw.extend(steps);
                    notes.push("hoist check: human steps".into());
                    pending = true;
                }
                _ => {
                    self.human(
                        "hoist-check",
                        format!("hoist check could not run here: {}", failure(&c, &o)),
                        "",
                        "hoist check",
                    );
                    notes.push("hoist check skipped".into());
                    pending = true;
                }
            }
        }
        if notes.is_empty() {
            return Ok((MAction::Skipped, "nothing to verify".into()));
        }
        Ok((
            if pending {
                MAction::Pending
            } else {
                MAction::Ok
            },
            notes.join("; "),
        ))
    }

    fn s_mode(&mut self) -> Res {
        let Some(mode) = self.args.mode.clone() else {
            return Ok((MAction::Skipped, "not asked (--mode)".into()));
        };
        if !self.p.bosun {
            return Ok((MAction::Skipped, "no .bosun/".into()));
        }
        let c = self.tool("bosun", &["--json", "migrate", "--to", &mode, "--dry-run"]);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        self.human(
            "bosun-mode",
            format!(
                "After this PR merges, move bosun to mode {mode} (it opens its own gated PR, owner approves)"
            ),
            "",
            &format!("bosun migrate --to {mode}"),
        );
        Ok((
            MAction::Pending,
            format!("planned: bosun migrate --to {mode}"),
        ))
    }

    /// Commits ahead of the default branch (the migration already exists from an earlier run).
    fn ahead(&self) -> u32 {
        let base = ["origin/HEAD", "origin/main", "origin/master"]
            .iter()
            .find(|b| self.git(&["rev-parse", "--verify", "--quiet", b]).code == 0);
        let Some(base) = base else { return 0 };
        let o = self.git(&["rev-list", "--count", &format!("{base}..HEAD")]);
        o.stdout.trim().parse().unwrap_or(0)
    }

    fn s_pr(&mut self) -> Res {
        if !self.args.pr {
            return Ok((MAction::Skipped, "not asked (--pr)".into()));
        }
        let c = Cmd::new("gh", &["repo", "view", "--json", "nameWithOwner"]).dir(&self.dir);
        let o = self.r.run(&c);
        let repo = json(&o)
            .and_then(|v| v["nameWithOwner"].as_str().map(String::from))
            .filter(|_| o.code == 0)
            .ok_or_else(|| failure(&c, &o))?;
        if let Some(pr) = gh::pr_view(self.r, &self.dir, &repo, &self.branch)
            && pr.state == "OPEN"
        {
            self.pr = Some(PrInfo {
                action: "existing",
                url: pr.url.clone(),
            });
            self.push()?;
            return Ok((MAction::Ok, format!("PR {} is open", pr.url)));
        }
        self.push()?;
        let title = format!("chore: migrate to keelstack v{}", self.target);
        let body = self.pr_body();
        let c = gh::pr_create_cmd(&self.dir, &repo, &self.branch, &title, &body);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        let url = o
            .stdout
            .lines()
            .rfind(|l| l.trim().starts_with("http"))
            .unwrap_or("")
            .trim()
            .to_string();
        self.pr = Some(PrInfo {
            action: "opened",
            url: url.clone(),
        });
        Ok((MAction::Done, format!("opened {url}")))
    }

    fn push(&self) -> Result<(), String> {
        let c = Cmd::new("git", &["push", "-u", "origin", &self.branch]).dir(&self.dir);
        let o = self.r.run(&c);
        if o.code != 0 {
            return Err(failure(&c, &o));
        }
        Ok(())
    }

    fn pr_body(&self) -> String {
        let mut b = format!(
            "Moves this repo to keelstack v{} with `keel migrate`.\n\n## Steps\n",
            self.target
        );
        for s in &self.steps {
            b.push_str(&format!(
                "- `{}` {}: {}\n",
                s.id,
                s.action.as_str(),
                s.detail
            ));
        }
        let list = build_checklist(&self.raw, &[]);
        if !list.is_empty() {
            b.push_str("\n## Left for a human\n");
            for e in &list {
                b.push_str(&format!("- [{}] {}", e.device, e.title));
                if !e.command.is_empty() {
                    b.push_str(&format!(" (`{}`)", e.command));
                }
                b.push('\n');
            }
        }
        b.push_str(BODY_TAIL);
        b
    }

    fn push_step(&mut self, id: &str, r: Res) -> bool {
        let (action, detail, ok) = match r {
            Ok((a, d)) => (a, d, true),
            Err(d) => (MAction::Failed, d, false),
        };
        self.steps.push(MStep {
            id: id.into(),
            action,
            detail,
        });
        ok
    }

    /// Undo this run: back to where it started, the branch deleted when keel made it.
    fn rollback(&self, start: &str, created: bool) -> Result<(), String> {
        let must = |o: Out, what: &str| -> Result<(), String> {
            if o.code == 0 {
                Ok(())
            } else {
                Err(format!("{what} failed: {}", o.stderr.trim()))
            }
        };
        must(self.git(&["reset", "--hard", start]), "git reset")?;
        must(self.git(&["clean", "-fd", "-e", ".keel"]), "git clean")?;
        if created {
            must(self.git(&["checkout", &self.orig]), "git checkout")?;
            must(self.git(&["branch", "-D", &self.branch]), "git branch -D")?;
        }
        Ok(())
    }
}

/// `tool from -> to` lines of a bosun `changed`/`behind` array.
fn behind_list(v: &Value) -> String {
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|i| {
                    format!(
                        "{} {} -> {}",
                        i["tool"].as_str().unwrap_or("?"),
                        i["from"].as_str().unwrap_or("?"),
                        i["to"].as_str().unwrap_or("?")
                    )
                })
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default()
}

fn human_steps(v: &Value) -> Vec<HumanStep> {
    v["human_steps"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|h| {
                    Some(HumanStep {
                        id: h["id"].as_str()?.to_string(),
                        title: h["title"].as_str()?.to_string(),
                        url: h["url"].as_str().unwrap_or("").to_string(),
                        command: String::new(),
                    })
                })
                .collect()
        })
        .unwrap_or_default()
}

/// `.keel/` is keel's scratch space: list it in `.git/info/exclude` so `git status` stays clean
/// and no tracked file (`.gitignore`) changes.
fn keep_scratch_untracked(git: &dyn Fn(&[&str]) -> Out, dir: &Path) {
    let o = git(&["rev-parse", "--git-path", "info/exclude"]);
    let rel = o.stdout.trim();
    if o.code != 0 || rel.is_empty() {
        return;
    }
    let path = dir.join(rel);
    let cur = std::fs::read_to_string(&path).unwrap_or_default();
    if cur.lines().any(|l| l.trim() == ".keel/") {
        return;
    }
    let mut next = cur;
    if !next.is_empty() && !next.ends_with('\n') {
        next.push('\n');
    }
    next.push_str(".keel/\n");
    let _ = path
        .parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|()| std::fs::write(&path, next));
}

/// An environment error (exit 3) whose message says how to fix it.
fn env_err(msg: impl Into<String>, fix: impl Into<String>) -> KeelError {
    KeelError::Env(format!("{}; fix: {}", msg.into(), fix.into()))
}

pub fn run(dir: &Path, args: &MigrateArgs, r: &dyn Runner) -> Result<MigrateReport, KeelError> {
    let target = args
        .to
        .clone()
        .unwrap_or_else(|| env!("CARGO_PKG_VERSION").to_string());
    if !valid_semver(&target) {
        return Err(KeelError::Fix {
            message: format!("--to {target:?} is not a release number"),
            fix: "keel migrate --to 0.23.0".into(),
        });
    }
    let p = detect(dir);
    if !(p.splice || p.bosun || p.hoist) {
        return Err(env_err(
            "nothing to migrate: no .splice/, .bosun/ or hoist.toml here",
            "run keel migrate from the repo root (-C DIR), or `keel up` to bootstrap a repo",
        ));
    }
    let gitc = |a: &[&str]| r.run(&Cmd::new("git", a).dir(dir));
    if gitc(&["rev-parse", "--is-inside-work-tree"]).code != 0 {
        return Err(env_err(
            "not a git checkout",
            "run keel migrate inside the repo's clone",
        ));
    }
    let orig = {
        let o = gitc(&["rev-parse", "--abbrev-ref", "HEAD"]);
        o.stdout.trim().to_string()
    };
    if orig.is_empty() || orig == "HEAD" {
        return Err(env_err(
            "HEAD is detached or has no commit",
            "git switch <branch> first",
        ));
    }
    let mut st = vec!["status", "--porcelain"];
    st.extend(NOT_KEEL);
    if !args.dry_run && !gitc(&st).stdout.trim().is_empty() {
        return Err(env_err(
            "the working tree has changes; keel migrate refuses a dirty tree (git is the undo button)",
            "commit or stash them, then rerun",
        ));
    }
    if args.pr && !args.dry_run {
        match gh::auth_ok(r) {
            None => {
                return Err(env_err(
                    "gh not found; --pr needs the GitHub CLI",
                    "install gh (https://cli.github.com) or run without --pr",
                ));
            }
            Some(false) => {
                return Err(env_err("gh is not logged in", "run `gh auth login`"));
            }
            Some(true) => {}
        }
    }
    let start = gitc(&["rev-parse", "HEAD"]).stdout.trim().to_string();
    if start.is_empty() {
        return Err(env_err("the repo has no commit yet", "make a first commit"));
    }
    let branch = format!("keel/migrate-v{target}");
    let mut m = Mig {
        r,
        dir: dir.to_path_buf(),
        target: target.clone(),
        dry: args.dry_run,
        args: args.clone(),
        pins: Pins::load(dir)?,
        p: p.clone(),
        steps: Vec::new(),
        raw: Vec::new(),
        branch: branch.clone(),
        orig: orig.clone(),
        commits: 0,
        snippet: Snippet {
            status: "not-checked",
            path: None,
            sha256: None,
            summary: String::new(),
        },
        before: None,
        pr: None,
    };

    let mut created = false;
    if !m.dry {
        if orig != branch {
            let exists = gitc(&[
                "rev-parse",
                "--verify",
                "--quiet",
                &format!("refs/heads/{branch}"),
            ]);
            let merged = exists.code == 0
                && gitc(&["merge-base", "--is-ancestor", &branch, "HEAD"]).code == 0;
            if merged {
                // An earlier migration PR was merged: its branch is only a leftover.
                let _ = gitc(&["branch", "-D", &branch]);
            } else if exists.code == 0 {
                return Err(env_err(
                    format!("branch {branch} already exists"),
                    format!(
                        "`git switch {branch}` and rerun to resume it, or `git branch -D {branch}`"
                    ),
                ));
            }
            let o = gitc(&["checkout", "-b", &branch]);
            if o.code != 0 {
                return Err(KeelError::Env(format!(
                    "cannot create {branch}: {}",
                    o.stderr.trim()
                )));
            }
            created = true;
        }
        keep_scratch_untracked(&gitc, dir);
        // The old snippet: the one kept from an earlier failed run, else what the installed bosun prints.
        if p.bosun {
            m.before = std::fs::read_to_string(dir.join(SNIPPET_BEFORE))
                .ok()
                .or_else(|| m.snippet_now());
            if let Some(b) = &m.before {
                let f = dir.join(SNIPPET_BEFORE);
                let _ = f
                    .parent()
                    .map_or(Ok(()), std::fs::create_dir_all)
                    .and_then(|()| std::fs::write(f, b));
            }
        }
    }

    let order = [
        "tools",
        "splice",
        "bosun-pin",
        "hoist",
        "setup-snippet",
        "verify",
        "mode",
        "pr",
    ];
    let mut failed: Option<usize> = None;
    for (i, id) in order.iter().enumerate() {
        if failed.is_some() {
            m.steps.push(MStep {
                id: (*id).into(),
                action: MAction::NotReached,
                detail: String::new(),
            });
            continue;
        }
        if *id == "pr" && (m.dry || (m.commits == 0 && m.ahead() == 0)) {
            m.steps.push(MStep {
                id: "pr".into(),
                action: MAction::Skipped,
                detail: if m.dry {
                    "dry-run: no push, no PR".into()
                } else {
                    "nothing changed: no PR".into()
                },
            });
            continue;
        }
        let res = match *id {
            "tools" => m.s_tools(),
            "splice" => m.s_splice(),
            "bosun-pin" => m.s_bosun_pin(),
            "hoist" => m.s_hoist(),
            "setup-snippet" => m.s_snippet(),
            "verify" => m.s_verify(),
            "mode" => m.s_mode(),
            _ => m.s_pr(),
        };
        if !m.push_step(id, res) {
            failed = Some(i);
        }
    }

    let mut recovery = None;
    let mut keep_branch = !m.dry;
    if let Some(i) = failed {
        let fid = order[i];
        if fid == "pr" {
            // The migration is committed and fine; only the push or PR failed.
            recovery = Some(format!(
                "the migration is committed on branch {branch} (nothing lost); fix the push or `gh` problem above, then rerun `keel migrate --pr`"
            ));
        } else if m.dry {
            recovery = Some("nothing was written; fix the problem above and rerun".into());
        } else {
            let undo = format!(
                "git reset --hard {start} && git clean -fd -e .keel{}",
                if created {
                    format!(" && git checkout {orig} && git branch -D {branch}")
                } else {
                    String::new()
                }
            );
            recovery = Some(match m.rollback(&start, created) {
                Ok(()) => format!(
                    "rolled back: {orig} is untouched{}; tools installed by npm stay installed. Fix step `{fid}` (see its detail), then rerun `keel migrate`",
                    if created {
                        format!(" and branch {branch} is deleted")
                    } else {
                        String::new()
                    }
                ),
                Err(e) => format!(
                    "rollback failed ({e}); restore by hand: {undo}. Then fix step `{fid}` and rerun `keel migrate`"
                ),
            });
            keep_branch = false;
        }
    }

    let changed = failed.is_none() && !m.dry && (m.commits > 0 || m.ahead() > 0);
    if failed.is_none() && !m.dry {
        let _ = std::fs::remove_file(dir.join(SNIPPET_BEFORE));
        if !changed && created {
            // Up to date: put the user back where they were and drop the empty branch.
            let _ = m.git(&["checkout", &orig]);
            let _ = m.git(&["branch", "-D", &branch]);
            keep_branch = false;
        }
    }
    if failed.is_none() && changed {
        match (&m.pr, m.args.pr) {
            (Some(pr), _) => {
                let (url, msg) = (
                    pr.url.clone(),
                    format!("Approve and merge the migration PR {}", pr.url),
                );
                m.human("approve-pr", msg, &url, "");
            }
            (None, false) => m.human(
                "open-pr",
                format!("Push {branch} and open the PR (keel never merges it)"),
                "",
                "keel migrate --pr",
            ),
            _ => {}
        }
    }

    let checklist = build_checklist(&m.raw, &[]);
    let human_step = checklist.first().map(|e| HumanStep {
        id: e.id.clone(),
        title: e.title.clone(),
        url: e.url.clone(),
        command: e.command.clone(),
    });
    let would_run = m.steps.iter().any(|s| s.action == MAction::WouldRun);
    let (status, exit_code) = if failed.is_some() {
        ("failed", 1)
    } else if m.dry && would_run {
        ("planned", 1)
    } else if human_step.is_some() {
        ("human", 5)
    } else {
        ("done", 0)
    };
    Ok(MigrateReport {
        command: "migrate",
        status,
        exit_code,
        target,
        dry_run: m.dry,
        from_branch: orig,
        branch: keep_branch.then_some(branch),
        pieces: p,
        steps: m.steps,
        changed,
        pr: m.pr,
        setup_snippet: m.snippet,
        checklist,
        human_step,
        recovery,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn release_numbers_are_x_y_z() {
        assert!(valid_semver("0.23.0"));
        for bad in [
            "",
            "1",
            "1.2",
            "1.2.3.4",
            "v1.2.3",
            "1.2.x",
            "1..3",
            "1.2.3-rc1",
        ] {
            assert!(!valid_semver(bad), "{bad}");
        }
    }

    #[test]
    fn version_is_the_last_word_without_v() {
        assert_eq!(
            version_of(&Out::ok("splice 0.23.0\n")).as_deref(),
            Some("0.23.0")
        );
        assert_eq!(version_of(&Out::ok("v0.23.0")).as_deref(), Some("0.23.0"));
        assert_eq!(version_of(&Out::with(1, "0.23.0", "")), None);
        assert_eq!(version_of(&Out::with(-1, "", "")), None);
    }

    #[test]
    fn snippet_summary_counts_lines_and_names_the_diff() {
        let s = snippet_summary("a\nb\nc\n", "a\nb\nd\ne\n");
        assert!(s.starts_with("2 lines added, 1 removed (sha256 "), "{s}");
        assert!(s.contains("diff .keel/cloud-setup.previous.sh .keel/cloud-setup.sh"));
    }

    #[test]
    fn detect_finds_only_what_is_on_disk() {
        let d = tempfile::tempdir().unwrap();
        let p = detect(d.path());
        assert!(!p.splice && !p.bosun && !p.hoist && !p.keel);
        std::fs::create_dir_all(d.path().join(".splice/channels")).unwrap();
        std::fs::write(d.path().join(".splice/channels/decisions.toml"), "").unwrap();
        std::fs::create_dir_all(d.path().join(".bosun")).unwrap();
        let p = detect(d.path());
        assert!(p.splice && p.bosun && p.decisions_channel && !p.bosun_channel && !p.hoist);
    }

    #[test]
    fn behind_list_reads_bosun_pin_json() {
        let v: Value =
            serde_json::from_str(r#"[{"tool":"bosun","from":"0.22.1","to":"0.23.0"}]"#).unwrap();
        assert_eq!(behind_list(&v), "bosun 0.22.1 -> 0.23.0");
        assert_eq!(behind_list(&Value::Null), "");
    }

    #[test]
    fn a_bad_target_is_a_usage_error() {
        let d = tempfile::tempdir().unwrap();
        let a = MigrateArgs {
            to: Some("latest".into()),
            ..MigrateArgs::default()
        };
        let e = run(d.path(), &a, &crate::exec::FakeRunner::new()).unwrap_err();
        assert_eq!(e.exit_code(), 2);
    }

    #[test]
    fn no_piece_is_an_environment_error_with_a_fix() {
        let d = tempfile::tempdir().unwrap();
        let e = run(
            d.path(),
            &MigrateArgs::default(),
            &crate::exec::FakeRunner::new(),
        )
        .unwrap_err();
        assert_eq!(e.exit_code(), 3);
        assert!(e.to_string().contains("nothing to migrate"));
    }

    #[test]
    fn registry_pin_reads_dist_integrity_of_both_packages() {
        let r = crate::exec::FakeRunner::new().on(&["npm", "view"], Out::ok("sha512-QUJD\n"));
        let pin = npm::registry_pin(&r, "splice", "0.23.0").unwrap();
        let s = pin.sha512.unwrap();
        assert_eq!(s.launcher, "QUJD");
        assert_eq!(s.platform.values().next().unwrap(), "QUJD");
        let calls = r.calls();
        assert!(calls[0].line().contains("@keelstackhq/splice@0.23.0"));
        assert!(calls[1].line().contains("@keelstackhq/splice-"));
        let none = crate::exec::FakeRunner::new().on(&["npm", "view"], Out::with(1, "", "E404"));
        assert!(npm::registry_pin(&none, "splice", "9.9.9").is_err());
    }
}
