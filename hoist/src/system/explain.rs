//! `hoist system explain` (spec §17.7): SYSTEM.md from system.toml alone, deterministic.

use super::check::path_of;
use super::{Credential, Provider, SystemFile};
use crate::error::HoistError;
use crate::report::{Action, Item, Report};
use std::path::Path;

pub const OUT: &str = "SYSTEM.md";

/// Table cell text: no pipes or newlines.
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn or_dash(s: Option<&str>) -> String {
    s.filter(|s| !s.is_empty()).map_or_else(|| "—".into(), cell)
}

fn join(v: impl IntoIterator<Item = String>) -> String {
    let v: Vec<String> = v.into_iter().collect();
    if v.is_empty() {
        "—".into()
    } else {
        cell(&v.join(", "))
    }
}

/// Mermaid node id: letters, digits and `_` only.
fn node(prefix: &str, id: &str) -> String {
    let s: String = id
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    format!("{prefix}_{s}")
}

fn provider_section(o: &mut String, p: &Provider, creds: &[&Credential]) {
    o.push_str(&format!("\n## {}\n\n", p.id));
    o.push_str("| capability | account | console | docs | CLIs | alternatives |\n");
    o.push_str("| --- | --- | --- | --- | --- | --- |\n");
    let clis = join(p.clis.iter().map(|c| {
        let mut s = c.tool.clone();
        if let Some(v) = &c.version {
            s += &format!(" {v}");
        }
        if let Some(m) = &c.mise {
            s += &format!(" (mise `{m}`)");
        }
        s
    }));
    o.push_str(&format!(
        "| {} | {} | {} | {} | {} | {} |\n",
        cell(&p.capability),
        or_dash(p.account.as_deref()),
        or_dash(p.console.as_deref()),
        or_dash(p.docs.as_deref()),
        clis,
        join(p.alternatives.iter().cloned()),
    ));
    if creds.is_empty() {
        return;
    }
    o.push_str("\n| credential | kind | role | purpose | storage | consumers | created | expires | rotate | status |\n");
    o.push_str("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for c in creds {
        o.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            cell(&c.id),
            c.kind.as_str(),
            cell(&c.role),
            cell(&c.purpose),
            join(c.storage.iter().map(|s| format!("`{}`", s.label()))),
            join(c.consumers.iter().map(|u| u.label())),
            or_dash(c.created_at.as_deref()),
            or_dash(c.expires_at.as_deref()),
            or_dash(c.rotate_every.as_deref()),
            format!("{:?}", c.status).to_lowercase(),
        ));
    }
}

/// The SYSTEM.md text.
pub fn render(sys: &SystemFile) -> String {
    let mut o = format!(
        "# System: {}\n\n<!-- Generated by `hoist system explain --write` from system.toml; do not edit. -->\n\n",
        sys.system.name
    );
    o.push_str(&format!("Owner: {}\n", sys.system.owner));
    if let Some(d) = &sys.system.description {
        o.push_str(&format!("\n{d}\n"));
    }
    o.push_str("\n```mermaid\nflowchart LR\n");
    o.push_str(&format!(
        "  repo[\"{}\"]\n",
        sys.system.name.replace('"', "'")
    ));
    for p in &sys.providers {
        o.push_str(&format!("  repo --> {}[\"{}\"]\n", node("p", &p.id), p.id));
    }
    for c in &sys.credentials {
        o.push_str(&format!(
            "  {} --> {}([\"{}\"])\n",
            node("p", &c.provider),
            node("c", &c.id),
            c.id
        ));
        for u in &c.consumers {
            let l = u.label();
            o.push_str(&format!(
                "  {} --> {}[/\"{}\"/]\n",
                node("c", &c.id),
                node("u", &l),
                l.replace('"', "'")
            ));
        }
    }
    for t in &sys.trusts {
        o.push_str(&format!(
            "  {} -. {} .-> repo\n",
            node("p", &t.provider),
            t.kind.as_str()
        ));
    }
    o.push_str("```\n");
    for p in &sys.providers {
        let creds: Vec<&Credential> = sys
            .credentials
            .iter()
            .filter(|c| c.provider == p.id)
            .collect();
        provider_section(&mut o, p, &creds);
    }
    if !sys.trusts.is_empty() {
        o.push_str("\n## Keyless trust\n\n| provider | kind | subject | replaces |\n| --- | --- | --- | --- |\n");
        for t in &sys.trusts {
            o.push_str(&format!(
                "| {} | {} | {} | {} |\n",
                cell(&t.provider),
                t.kind.as_str(),
                cell(&t.subject),
                or_dash(t.replaces.as_deref())
            ));
        }
    }
    o.push_str("\n## Rotation\n");
    for c in &sys.credentials {
        o.push_str(&format!("\n### {}\n\n", c.id));
        let mut facts = Vec::new();
        if let Some(p) = &c.principal {
            facts.push(format!("- Principal: {p}"));
        }
        if !c.scopes.is_empty() {
            facts.push(format!("- Scopes: {}", c.scopes.join(", ")));
        }
        if !c.resources.is_empty() {
            facts.push(format!("- Resources: {}", c.resources.join(", ")));
        }
        if let Some(v) = &c.created_via {
            facts.push(format!("- Created via: `{v}`"));
        }
        if let Some(v) = &c.max_ttl {
            facts.push(format!("- Max TTL: {v}"));
        }
        match &c.rotation {
            Some(r) => {
                facts.push(format!("- Strategy: {}", r.strategy.as_str()));
                if let Some(cmd) = &r.command {
                    facts.push(format!("- Command: `{cmd}`"));
                }
                for (i, s) in r.steps.iter().enumerate() {
                    facts.push(format!("{}. {s}", i + 1));
                }
            }
            None => facts.push("- Strategy: not described (add `rotation` to system.toml)".into()),
        }
        if let Some(n) = &c.notes {
            facts.push(format!("- Notes: {n}"));
        }
        o.push_str(&facts.join("\n"));
        o.push('\n');
    }
    o
}

pub fn system_explain(
    dir: &Path,
    file: Option<&Path>,
    write: bool,
    check: bool,
) -> Result<Report, HoistError> {
    if write && check {
        return Err(HoistError::Usage(
            "--write and --check exclude each other".into(),
        ));
    }
    let path = path_of(dir, file);
    let sys = SystemFile::load(&path)?;
    let md = render(&sys);
    let out = path.parent().unwrap_or(dir).join(OUT);
    let current = std::fs::read_to_string(&out).ok();
    let item = |action, reason: &str| Item {
        area: "system".into(),
        kind: "file".into(),
        key: OUT.into(),
        action,
        reason: reason.into(),
        source: super::FILE.into(),
        verify: None,
    };
    let (items, text) = if write {
        let action = match &current {
            Some(c) if *c == md => Action::Ok,
            Some(_) => Action::Update,
            None => Action::Create,
        };
        if action != Action::Ok {
            std::fs::write(&out, &md).map_err(|e| HoistError::Config {
                file: OUT.into(),
                message: format!("cannot write: {e}"),
            })?;
        }
        (vec![item(action, "written from system.toml")], None)
    } else if check {
        let it = match &current {
            Some(c) if *c == md => item(Action::Ok, "matches system.toml"),
            Some(_) => item(Action::Drift, "stale: run `hoist system explain --write`"),
            None => item(Action::Drift, "missing: run `hoist system explain --write`"),
        };
        (vec![it], None)
    } else {
        let mut items: Vec<Item> = sys
            .providers
            .iter()
            .map(|p| Item {
                kind: "provider".into(),
                key: p.id.clone(),
                reason: p.capability.clone(),
                ..item(Action::Ok, "")
            })
            .collect();
        items.extend(sys.credentials.iter().map(|c| Item {
            kind: "credential".into(),
            key: c.id.clone(),
            reason: format!("{} {} for {}", c.provider, c.kind.as_str(), c.role),
            ..item(Action::Ok, "")
        }));
        (items, Some(md))
    };
    // Write: exit 0 (the file now matches); check: drift is 1. Write's action is never drift.
    let exit_code = if write {
        0
    } else {
        crate::ops::check::exit_code(&items)
    };
    Ok(Report {
        command: "system explain".into(),
        items,
        human_steps: Vec::new(),
        exit_code,
        text,
        hint: None,
    })
}
