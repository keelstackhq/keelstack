import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, test } from "vite-plus/test";
import { hasLiteralPin } from "../lib/pins.ts";
import { tagCommits, versions } from "./versions.ts";
import { diffGenerated, driftMessage, generate } from "../lib/generate.ts";

test("committed generated docs match docs-src and versions.ts", () => {
  expect(() =>
    execFileSync("node", ["scripts/gen-docs.ts", "--check"], { stdio: "pipe", encoding: "utf8" }),
  ).not.toThrow();
});

test("every generated header names its source repo-relative (apps/site/docs-src/<file>)", () => {
  for (const [path, content] of generate()) {
    if (!path.endsWith(".md")) continue;
    const rel = path.replace(/^src\/pages\/docs\//, "");
    expect(content, path).toContain(
      `<!-- generated by scripts/gen-docs.ts from apps/site/docs-src/${rel}; edit that -->`,
    );
  }
});

const read = (p: string) => (p === "a.md" ? "one" : "changed");

test("diffGenerated returns the paths whose committed copy differs", () => {
  const map = new Map([
    ["a.md", "one"],
    ["b.md", "two"],
  ]);
  expect(diffGenerated(map, read)).toEqual(["b.md"]);
  expect(diffGenerated(map, () => undefined)).toEqual(["a.md", "b.md"]);
});

const readOrphan = (p: string) =>
  p === "src/pages/docs/old.md" ? "<!-- generated by scripts/gen-docs.ts from x -->" : "hand";

test("an orphan generated page is reported, a hand-written page is not", () => {
  const existing = ["src/pages/docs/old.md", "src/pages/docs/hand.md"];
  expect(diffGenerated(new Map(), readOrphan, existing)).toEqual(["src/pages/docs/old.md"]);
});

test("the drift message names each file and the gen command", () => {
  const m = driftMessage(["src/pages/docs/a.md", "src/pages/docs/b.md"]);
  expect(m).toContain("src/pages/docs/a.md");
  expect(m).toContain("src/pages/docs/b.md");
  expect(m).toContain("pnpm --filter @keelstackhq/site gen");
});

const walk = (d: string): string[] =>
  readdirSync(d, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)],
  );

describe("docs-src holds no literal current pins", () => {
  const dir = join(dirname(fileURLToPath(import.meta.url)), "../../docs-src");
  const allowFile = join(dir, ".literal-allow");
  const allow = new Set(
    walk(dir).includes(allowFile) ? readFileSync(allowFile, "utf8").split("\n") : [],
  );

  test("every pin is a token", () => {
    const hits: string[] = [];
    for (const f of walk(dir).filter((p) => p.endsWith(".md"))) {
      readFileSync(f, "utf8")
        .split("\n")
        .forEach((line, i) => {
          if (allow.has(line)) return;
          if (hasLiteralPin(line, versions, tagCommits))
            hits.push(`${relative(dir, f)}:${i + 1}: ${line.slice(0, 100)}`);
        });
    }
    expect(hits).toEqual([]);
  });
});

test("every .literal-allow entry still occurs in a docs-src file", () => {
  const dir = join(dirname(fileURLToPath(import.meta.url)), "../../docs-src");
  const entries = readFileSync(join(dir, ".literal-allow"), "utf8").split("\n").filter(Boolean);
  const lines = new Set(
    walk(dir)
      .filter((p) => p.endsWith(".md"))
      .flatMap((f) => readFileSync(f, "utf8").split("\n")),
  );
  expect(entries.filter((e) => !lines.has(e))).toEqual([]);
});
