// Renders docs-src/**/*.md into src/pages/docs/ (pure: reads files, writes nothing).
// Imported by scripts/gen-docs.ts under Node, so it uses .ts extensions and only render.ts.
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { verifiedOn, versions } from "../data/versions.ts";
import { buildCtx, renderTemplate } from "./render.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );

const FRONTMATTER = /^---\n[\s\S]*?\n---\n/;

/**
 * Output path -> rendered content, before formatting. Paths are relative to apps/site, except
 * `agents/**`, which are relative to the repo root (`outPath`).
 */
export const outPath = (p: string): string =>
  p.startsWith("agents/") ? join(root, "../..", p) : join(root, p);

/** Repo-relative (to apps/site) output path -> rendered content, before formatting. */
export function generate(): Map<string, string> {
  const adopt = JSON.parse(readFileSync(join(root, "src/data/hull/adopt.json"), "utf8")) as {
    hosted: Record<string, { ref: string; sha256: string }>;
  };
  // The prompt pins the assessment of the hull tag the page shows (a legacy tag before the
  // first release), not whichever one was copied last.
  const hosted = adopt.hosted[versions.hull];
  if (!hosted) {
    throw new Error(
      `generate: hull ${versions.hull} is not hosted in src/data/hull/adopt.json (hosted: ${Object.keys(adopt.hosted).join(", ")})`,
    );
  }
  const ctx = buildCtx(undefined, {
    assessUrl: `/assess/${versions.hull}.mjs`,
    assessSha: hosted.sha256,
  });
  const out = new Map<string, string>();
  const srcDir = join(root, "docs-src");
  for (const abs of walk(srcDir).filter((f) => f.endsWith(".md"))) {
    const rel = relative(srcDir, abs);
    const rendered = renderTemplate(readFileSync(abs, "utf8"), ctx, rel);
    const header = `<!-- generated by scripts/gen-docs.ts from apps/site/docs-src/${rel}; edit that -->\n`;
    const fm = rendered.match(FRONTMATTER)?.[0] ?? "";
    const target = rel === "agents/README.md" ? rel : `src/pages/docs/${rel}`;
    out.set(target, fm + header + rendered.slice(fm.length));
  }
  out.set(
    "agents/versions.json",
    JSON.stringify({ versions, verified: verifiedOn }, null, 2) + "\n",
  );
  return out;
}

export const GEN_MARK = "<!-- generated by scripts/gen-docs.ts";

/**
 * Paths whose committed copy (`read` returns undefined when missing) differs from the map, plus
 * orphans: `existing` pages that carry the generated header but have no docs-src source.
 */
export function diffGenerated(
  map: Map<string, string>,
  read: (path: string) => string | undefined,
  existing: string[] = [],
): string[] {
  const changed = [...map].filter(([path, content]) => read(path) !== content).map(([p]) => p);
  const orphans = existing.filter((p) => !map.has(p) && read(p)?.includes(GEN_MARK));
  return [...changed, ...orphans];
}

export const driftMessage = (paths: string[]): string =>
  `gen-docs: out of date:\n${paths.map((p) => `  ${p}`).join("\n")}\n` +
  "Edit docs-src/ or versions.ts, then run: pnpm --filter @keelstackhq/site gen";

/** Every page under src/pages/docs (repo-relative to apps/site), for orphan detection. */
export const existingDocs = (): string[] =>
  walk(join(root, "src/pages/docs"))
    .filter((f) => f.endsWith(".md"))
    .map((f) => relative(root, f));
